def _execute_sheet_command(command: str) -> tuple[dict[str, Any], str, str]:
    completed = subprocess.run(
        shlex.split(command),
        cwd=REPO_ROOT,
        check=False,
        text=True,
        capture_output=True,
    )
    if completed.returncode != 0:
        raise SheetRenderError(
            f"documented command exited {completed.returncode}: {completed.stderr.strip()}"
        )
    try:
        payload = json.loads(completed.stdout)
        agreement = payload["comparison"]["direction_gate_outcomes_agree"]
    except (json.JSONDecodeError, KeyError, TypeError) as exc:
        raise SheetRenderError("documented command did not emit the expected JSON payload") from exc
    if not isinstance(agreement, bool):
        raise SheetRenderError("documented command emitted a non-boolean agreement field")
    fragment = f'"direction_gate_outcomes_agree": {str(agreement).lower()}'
    if fragment not in completed.stdout:
        raise SheetRenderError("documented command stdout does not contain its agreement fragment")
    return payload, fragment, "agree" if agreement else "disagree"


