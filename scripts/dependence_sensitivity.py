class SheetRenderError(RuntimeError):
    """Raised when a generated-sheet source cannot be resolved exactly."""


def _repo_relative(path: Path) -> str:
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError as exc:
        raise SheetRenderError(f"sheet source is outside the repository: {path}") from exc


def _format_decimal(value: int | float, precision: int) -> str:
    return f"{float(value):.{precision}f}"


def _format_compact(value: int | float) -> str:
    return str(int(value)) if float(value).is_integer() else str(float(value))


def _format_interval(interval: dict[str, float]) -> str:
    return f"[{interval['lower']:.6f}, {interval['upper']:.6f}]"


def _function_citation(path: Path, name: str) -> str:
    try:
        source = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise SheetRenderError(f"cannot read citation source {_repo_relative(path)}: {exc}") from exc
    try:
        tree = ast.parse(source, filename=str(path))
    except SyntaxError as exc:
        raise SheetRenderError(f"cannot parse citation source {_repo_relative(path)}: {exc}") from exc
    definitions = [
        node
        for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == name
    ]
    if len(definitions) != 1:
        raise SheetRenderError(
            f"expected exactly one definition of {name!r} in {_repo_relative(path)}; "
            f"found {len(definitions)}"
        )
    return f"`{name}` (`{_repo_relative(path)}`, line {definitions[0].lineno})"


def _validate_config_field_names() -> None:
    try:
        tree = ast.parse(
            CONFIG_GENERATOR_PATH.read_text(encoding="utf-8"),
            filename=str(CONFIG_GENERATOR_PATH),
        )
    except (OSError, SyntaxError) as exc:
        raise SheetRenderError(f"cannot inspect config generator: {exc}") from exc
    string_literals = {
        node.value
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str)
    }
    missing = sorted(CONFIG_FIELD_NAMES - string_literals)
    if missing:
        raise SheetRenderError(
            "config generator is missing registered field name(s): " + ", ".join(missing)
        )


def _markdown_heading_anchor(heading: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9_ -]", "", heading).strip().lower()
    return slug.replace(" ", "-")


def _h30_slots() -> dict[str, str]:
    try:
        text = RETENSING_PLAN_PATH.read_text(encoding="utf-8")
    except OSError as exc:
        raise SheetRenderError(f"cannot read retensing plan: {exc}") from exc
    sections = re.findall(r"^### (H30\b[^\n]*)\n(?P<body>.*?)(?=^### |\Z)", text, re.MULTILINE | re.DOTALL)
    if len(sections) != 1:
        raise SheetRenderError(f"expected exactly one H30 section; found {len(sections)}")
    heading, body = sections[0]
    replacements = re.findall(r"^\*\*Replacement:\*\* (.+)$", body, re.MULTILINE)
    if len(replacements) != 1:
        raise SheetRenderError(
            f"expected exactly one H30 replacement paragraph; found {len(replacements)}"
        )
    return {
        "h30_replacement": replacements[0],
        "h30_link": (
            f"{RETENSING_PLAN_PATH.name}#{_markdown_heading_anchor(heading)}"
        ),
    }


def _anchor_quote_pattern(quote_template: str) -> tuple[re.Pattern[str], tuple[str, ...]]:
    pieces: list[str] = ["^"]
    slot_names: list[str] = []
    cursor = 0
    for match in Template.pattern.finditer(quote_template):
        pieces.append(re.escape(quote_template[cursor : match.start()]))
        name = match.group("named") or match.group("braced")
        if name is None:
            raise SheetRenderError(f"unsupported draft-anchor template token: {match.group(0)!r}")
        if name in slot_names:
            raise SheetRenderError(f"duplicate draft-anchor slot: {name}")
        slot_names.append(name)
        pieces.append(f"(?P<{name}>[0-9]+)")
        cursor = match.end()
    pieces.append(re.escape(quote_template[cursor:]))
    return re.compile("".join(pieces)), tuple(slot_names)


def _draft_anchor_slots(template_text: str) -> dict[str, str]:
    placement_pattern = re.compile(
        r"^\| (?P<site>(?:DS|PG)-SENS-[0-9]+) [^|\n]*\| `(?P<quote>[^`\n]+)`",
        re.MULTILINE,
    )
    placements = tuple(placement_pattern.finditer(template_text))
    observed_sites = {match.group("site") for match in placements}
    if observed_sites != set(DRAFT_LINE_SLOT_BY_SITE) or len(placements) != len(observed_sites):
        raise SheetRenderError(
            "template draft-anchor sites differ from the registered placement set"
        )
    try:
        draft_lines = DRAFT_PATH.read_text(encoding="utf-8").splitlines()
    except OSError as exc:
        raise SheetRenderError(f"cannot read frozen draft: {exc}") from exc
    slots: dict[str, str] = {}
    for placement in placements:
        site = placement.group("site")
        quote_pattern, quote_slots = _anchor_quote_pattern(placement.group("quote"))
        matches = [
            (line_number, match)
            for line_number, line in enumerate(draft_lines, start=1)
            if (match := quote_pattern.match(line)) is not None
        ]
        if len(matches) != 1:
            raise SheetRenderError(
                f"draft anchor for {site} must occur exactly once; found {len(matches)}"
            )
        line_number, quote_match = matches[0]
        slots[DRAFT_LINE_SLOT_BY_SITE[site]] = str(line_number)
        for name in quote_slots:
            value = quote_match.group(name)
            if name in slots and slots[name] != value:
                raise SheetRenderError(f"draft-anchor slot {name} resolves inconsistently")
            slots[name] = value
    return slots


