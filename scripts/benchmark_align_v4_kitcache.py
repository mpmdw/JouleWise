#!/usr/bin/env python3
"""Synthetic kit/receipt timings and exact legacy equality; no probes or data.

Run from a clone containing the baseline Git ref. All generated bytes
and synthetic receipts live in a temporary directory. This does not
arm a session or make a registration admissible.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import statistics
import subprocess
import sys
import tempfile
import time
import types
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts import align_v4_kit as kit
from joulewise.align.apple import v4_registration as reg
from tests.align.test_v4_kitcache import generation_fixture, receipt_fixture


def baseline_module(ref, relative):
    raw = subprocess.run(['git', 'show', f'{ref}:{relative}'], cwd=ROOT,
                         capture_output=True, check=True).stdout
    module = types.ModuleType('kitcache_baseline_' + Path(relative).stem)
    # Both generators bind the same *current* generator-file digest. This
    # isolates implementation equality from the intentional provenance update.
    module.__file__ = str(ROOT / relative)
    exec(compile(raw, module.__file__, 'exec'), module.__dict__)
    return module


def measure(fn, rounds):
    samples = []
    for _ in range(rounds):
        start = time.perf_counter()
        fn()
        samples.append(time.perf_counter() - start)
    return dict(median_s=statistics.median(samples), samples_s=samples)


def refusal(fn):
    try:
        fn()
    except ValueError as exc:
        return str(exc)
    raise AssertionError('synthetic pending registration unexpectedly admitted')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--baseline-ref', default='origin/align/2026-11-08-v4-r11')
    parser.add_argument('--rounds', type=int, default=5)
    args = parser.parse_args(argv)
    if args.rounds < 1:
        parser.error('--rounds must be positive')
    old_kit = baseline_module(args.baseline_ref, 'scripts/align_v4_kit.py')
    old_reg = baseline_module(args.baseline_ref, 'joulewise/align/apple/v4_registration.py')
    with tempfile.TemporaryDirectory(prefix='align-v4-kitcache-synthetic-') as tmp:
        root = Path(tmp)
        old_output, new_output = root/'legacy-kit', root/'new-kit'
        receipt_root = root/'receipt'
        receipt_root.mkdir()
        receipt = receipt_fixture(receipt_root)
        legacy_files = old_kit.generate(old_output)
        current_files = kit.generate(new_output)
        assert current_files == legacy_files
        assert all((new_output/p).read_bytes() == raw for p, raw in legacy_files.items())
        legacy_refusal = refusal(lambda: old_kit.generate(old_output, check=True))
        assert refusal(lambda: kit.generate(new_output, check=True)) == legacy_refusal
        assert old_reg.validate_receipt(receipt, receipt_root) == reg.validate_receipt(receipt, receipt_root)
        filled_source = root/'filled-source'
        filled_source.mkdir()
        generation_fixture(filled_source)
        old_filled = root/'legacy-filled'
        new_filled = root/'new-filled'
        filled_files = old_kit.generate(old_filled, source_root=filled_source)
        assert kit.generate(new_filled, source_root=filled_source) == filled_files
        assert all((new_filled/p).read_bytes() == raw for p, raw in filled_files.items())
        results = dict(python=sys.version, baseline=args.baseline_ref,
                       generated_files=len(current_files), receipt_artifacts=len(reg.ARTIFACTS),
                       receipt_bindings=len(reg.ARTIFACTS)+2, exact_bytes_equal=True,
                       pending_refusal_equal=True, filled_sizing_bytes_equal=True)
        def check_pending(module, output):
            message = refusal(lambda: module.generate(output, check=True))
            assert message == legacy_refusal
        def static_arm(module, output, receipt_validator):
            # A component-only composition: byte regeneration/comparison plus
            # receipt binding. All other arm/live gates remain outside timing.
            with patch.object(module, 'require_w1_ready', side_effect=lambda root:
                              receipt_validator(receipt, receipt_root)):
                module.generate(output, source_root=filled_source, check=True)
        operations = {
            'generate_legacy': lambda: old_kit.generate(old_output),
            'generate_batched': lambda: kit.generate(new_output),
            'generate_filled_legacy': lambda: old_kit.generate(old_filled, source_root=filled_source),
            'generate_filled_batched': lambda: kit.generate(new_filled, source_root=filled_source),
            'check_pending_legacy': lambda: check_pending(old_kit, old_output),
            'check_pending_batched': lambda: check_pending(kit, new_output),
            'receipt_legacy': lambda: old_reg.validate_receipt(receipt, receipt_root),
            'receipt_current': lambda: reg.validate_receipt(receipt, receipt_root),
            'arm_static_synthetic_legacy': lambda: static_arm(old_kit, old_filled, old_reg.validate_receipt),
            'arm_static_synthetic_current': lambda: static_arm(kit, new_filled, reg.validate_receipt),
        }
        for name, operation in operations.items():
            results[name] = measure(operation, args.rounds)
            print(name, results[name]['median_s'], file=sys.stderr, flush=True)
        # Model the repeated negative checks in the existing receipt test:
        # each member drifts once, with all earlier paths restored in order.
        mutation_refusals = {}
        def mutations(label, validator):
            messages = []
            for path in reg.ARTIFACTS:
                target = receipt_root/path
                raw = target.read_bytes()
                target.write_bytes(raw+b'synthetic drift')
                try:
                    messages.append(refusal(lambda: validator(receipt, receipt_root)))
                finally:
                    target.write_bytes(raw)
            mutation_refusals[label] = messages
        results['receipt_mutations_legacy'] = measure(lambda: mutations('legacy', old_reg.validate_receipt), 1)
        results['receipt_mutations_current'] = measure(lambda: mutations('current', reg.validate_receipt), 1)
        assert mutation_refusals['legacy'] == mutation_refusals['current']
        results['receipt_mutation_refusals_equal'] = True
        print(json.dumps(results, indent=2, sort_keys=True))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
