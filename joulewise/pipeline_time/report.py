"""Weekly pipeline-time report (RL-127 term 9).

Inputs: the timing ledger, CI run metadata (`gh run list`), merged PRs
(`gh pr list`) and RUN_STATE item stamps. Output: Markdown plus a short
summary. `build` is pure; the script gathers the inputs.

MBP utilisation is estimated from item stamps, not from a utilisation log:
- session time: each arm item's `t0` (an ARMED heading or a pointer `armed`
  key) to the first later CLOSED/REFUSED item or re-arm (else its latest end,
  else now). An arm refused at t0 but noticed late counts as session time until
  the refusal item, which is how the MBP was actually held;
- other MBP work: each magistrate-owned unarmed pointer from its item stamp to
  the next item's stamp, capped by its deadline and at 12 h;
- idle: the rest of the window.
"""
from __future__ import annotations

from dataclasses import dataclass
import statistics
import time

from joulewise.pipeline_time import budgets, ledger, runstate

WORK_CAP_S = 12 * 3600


@dataclass
class Inputs:
    start: float
    end: float
    ledger_rows: list
    ci_runs: list | None
    prs: list | None
    run_state: runstate.RunState | None
    state_only: dict  # head sha -> bool


def _h(seconds: float) -> str:
    return f"{seconds / 3600:.2f}"


def _m(seconds: float) -> str:
    return f"{seconds / 60:.1f}"


def _day(epoch: float) -> str:
    return time.strftime("%Y-%m-%d %H:%M %Z", time.localtime(epoch))


def merge_intervals(intervals):
    merged = []
    for lo, hi in sorted(i for i in intervals if i[1] > i[0]):
        if merged and lo <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], hi)
        else:
            merged.append([lo, hi])
    return merged


def clip(intervals, start, end):
    return [(max(lo, start), min(hi, end)) for lo, hi in intervals if hi > start and lo < end]


def total(intervals) -> float:
    return sum(hi - lo for lo, hi in merge_intervals(intervals))


def mbp_intervals(rs: runstate.RunState, now: float):
    """(session intervals, other-work intervals, gaps [(close item, next arm item or None, gap_s, code_changed)])."""
    ordered = rs.ordered()
    sessions, work, gaps = [], [], []
    arm_keys = {item.key for item in rs.arm_items()}
    for index, item in enumerate(ordered):
        later = ordered[index + 1:]
        if item.key in arm_keys:
            fields = runstate.arm_fields(item)
            t0 = fields["t0"] or item.stamp
            if t0 is None:
                continue
            # A session ends at its close or refusal item, or at the next arm (a re-arm ends the last one).
            ender = next((o for o in later if o.stamp and (o.classes & {"closed", "refused"} or o.key in arm_keys)), None)
            end = ender.stamp if ender else min(fields["latest_end"] or now, now)
            sessions.append((t0, max(t0, end)))
        elif item.pointer and item.pointer.get("owner", "").strip().lower() == "magistrate" and item.stamp:
            nxt = next((o.stamp for o in later if o.stamp and o.stamp > item.stamp), None)
            cap = min(item.stamp + WORK_CAP_S, item.pointer_times.get("deadline") or item.stamp + WORK_CAP_S, now)
            end = min(nxt, cap) if nxt else cap
            work.append((item.stamp, max(item.stamp, end)))
    ends = [i for i in ordered if i.classes & {"closed", "refused"} and i.stamp]
    previous_end = None
    for end_item in ends:
        if previous_end is not None and not any(previous_end.key < k < end_item.key for k in arm_keys):
            continue  # a second close item for the same session
        previous_end = end_item
        nxt = next((o for o in ordered if o.key > end_item.key and o.key in arm_keys and o.stamp), None)
        until = nxt.stamp if nxt else now
        between = [o for o in ordered if end_item.key < o.key and (nxt is None or o.key < nxt.key)]
        gaps.append((end_item, nxt, max(0.0, until - end_item.stamp), runstate.code_changed(between)))
    return sessions, work, gaps


def ci_duration(run: dict) -> float | None:
    start = runstate.parse_time(run.get("startedAt") or run.get("createdAt"))
    end = runstate.parse_time(run.get("updatedAt"))
    if start is None or end is None or end < start:
        return None
    return end - start


def _stats(values):
    if not values:
        return "-", "-", "-"
    ordered = sorted(values)
    p90 = ordered[min(len(ordered) - 1, int(round(0.9 * (len(ordered) - 1))))]
    return _m(statistics.median(ordered)), _m(p90), _m(ordered[-1])


def build(inp: Inputs) -> tuple[str, list[str]]:
    lines, summary, sinks = [], [], []
    window = inp.end - inp.start
    lines += [f"# Pipeline time report, {time.strftime('%Y-%m-%d', time.localtime(inp.start))} to "
              f"{time.strftime('%Y-%m-%d', time.localtime(inp.end))}", "",
              f"Generated by `scripts/pipeline_time_report.py` at {_day(time.time())} (RL-127 term 9). "
              f"Window {_day(inp.start)} to {_day(inp.end)} ({_h(window)} h). "
              "Budgets are RL-127 term 6; an overrun is more than 1.5 x the budget. "
              "Structure only: no measurement, custody or result file is read.", ""]

    # Ledger
    _open_rows, ended = ledger.pair_entries(inp.ledger_rows)
    in_window = [r for r in ended if r.get("end_epoch_s") and inp.start <= float(r["end_epoch_s"]) <= inp.end]
    open_rows = [r for r in _open_rows if r.get("start_epoch_s") and float(r["start_epoch_s"]) <= inp.end]
    lines += ["## Timing ledger", ""]
    if not in_window and not open_rows:
        lines += ["No ledger rows in the window. Long jobs are not yet running under "
                  "`scripts/timing_ledger.py run`; RL-127 term 7 requires it.", ""]
        summary.append("ledger: no rows in window")
    else:
        by_stage = {}
        for row in in_window:
            by_stage.setdefault(row.get("stage") or "?", []).append(row)
        lines += ["| Stage | Runs | Hours | Median min | Worst min | Budget min | Over 1.5x |", "|---|---|---|---|---|---|---|"]
        for stage, rows in sorted(by_stage.items(), key=lambda kv: -sum(float(r["wall_s"]) for r in kv[1])):
            walls = [float(r["wall_s"]) for r in rows]
            budget = rows[0].get("budget_s")
            over = [r for r in rows if r.get("budget_s") and float(r["wall_s"]) > budgets.ALARM_FACTOR * float(r["budget_s"])]
            lines.append(f"| {stage} | {len(rows)} | {_h(sum(walls))} | {_m(statistics.median(walls))} | "
                         f"{_m(max(walls))} | {_m(float(budget)) if budget else '-'} | {len(over)} |")
            sinks.append((sum(walls), f"ledger stage `{stage}`: {len(rows)} runs"))
        lines.append("")
        overruns = [r for r in in_window if r.get("budget_s") and float(r["wall_s"]) > budgets.ALARM_FACTOR * float(r["budget_s"])]
        if overruns:
            lines += ["Overruns (profile before retry, RL-127 term 6):", ""]
            for row in sorted(overruns, key=lambda r: -float(r["wall_s"])):
                label = row.get("stage") + (f"/{row['phase']}" if row.get("phase") else "")
                lines.append(f"- `{label}` run `{row['run_id']}` on {row.get('host')}: {_m(float(row['wall_s']))} min, "
                             f"{float(row['wall_s']) / float(row['budget_s']):.1f}x budget, exit {row.get('exit')}, "
                             f"cpu {row.get('cpu_s', '-')} s")
            lines.append("")
        if open_rows:
            lines.append(f"Open at the window end: {len(open_rows)} row(s) without an end marker.")
            lines.append("")
        summary.append(f"ledger: {len(in_window)} finished rows, {len(overruns)} overruns")

    # CI
    lines += ["## CI", ""]
    if inp.ci_runs is None:
        lines += ["CI run list unavailable (`gh run list` failed).", ""]
        summary.append("CI: unavailable")
    else:
        runs = [r for r in inp.ci_runs if (runstate.parse_time(r.get("createdAt")) or 0) >= inp.start
                and (runstate.parse_time(r.get("createdAt")) or 0) <= inp.end and r.get("status") == "completed"]
        groups = {}
        for run in runs:
            duration = ci_duration(run)
            if duration is None:
                continue
            groups.setdefault((run.get("workflowName"), run.get("event")), []).append((run, duration))
        lines += ["| Workflow | Event | Runs | Median min | p90 min | Worst min | Run-hours | Over 45 min | Cancelled run-hours | Re-runs |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for (workflow, event), rows in sorted(groups.items(), key=lambda kv: -sum(d for _, d in kv[1])):
            durations = [d for _, d in rows]
            med, p90, worst = _stats(durations)
            over = sum(1 for d in durations if d > budgets.ALARM_FACTOR * budgets.BUDGETS_S["pr-ci"])
            cancelled = sum(d for r, d in rows if r.get("conclusion") == "cancelled")
            reruns = sum(1 for r, _ in rows if int(r.get("attempt") or 1) > 1)
            lines.append(f"| {workflow} | {event} | {len(rows)} | {med} | {p90} | {worst} | {_h(sum(durations))} | "
                         f"{over} | {_h(cancelled)} | {reruns} |")
            if workflow == "ci":
                sinks.append((sum(durations), f"CI `{workflow}` on {event}: {len(rows)} runs, {over} over 45 min"))
        lines.append("")
        push = [(r, d) for r, d in groups.get(("ci", "push"), [])]
        if push:
            state_only = [(r, d) for r, d in push if inp.state_only.get(r.get("headSha"))]
            slow = [d for _, d in state_only if d > budgets.ALARM_FACTOR * budgets.BUDGETS_S["state-only-ci"]]
            lines += [f"State-only pushes to main: {len(state_only)} of {len(push)} `ci` push runs "
                      f"({_h(sum(d for _, d in state_only))} run-hours); {len(slow)} took more than 1.5 x 5 min.", ""]
        ci_runs = groups.get(("ci", "pull_request"), [])
        summary.append(f"CI: {len(runs)} completed runs; ci/pull_request median "
                       f"{_stats([d for _, d in ci_runs])[0]} min")

    # PRs
    lines += ["## PR cycle", ""]
    if inp.prs is None:
        lines += ["Merged PR list unavailable.", ""]
    else:
        cycles = []
        for pr in inp.prs:
            merged = runstate.parse_time(pr.get("mergedAt"))
            opened = runstate.parse_time(pr.get("createdAt"))
            if merged and opened and inp.start <= merged <= inp.end:
                cycles.append((merged - opened, pr))
        if cycles:
            values = [c for c, _ in cycles]
            worst = max(cycles, key=lambda c: c[0])
            lines += [f"{len(cycles)} PRs merged; open-to-merge median {_h(statistics.median(values))} h, "
                      f"worst {_h(worst[0])} h (#{worst[1].get('number')}).", ""]
            summary.append(f"PRs: {len(cycles)} merged, median open-to-merge {_h(statistics.median(values))} h")
        else:
            lines += ["No PRs merged in the window.", ""]

    # MBP
    lines += ["## MBP utilisation (estimated from RUN_STATE item stamps)", ""]
    if inp.run_state is None:
        lines += ["RUN_STATE unavailable.", ""]
    else:
        sessions, work, gaps = mbp_intervals(inp.run_state, inp.end)
        session_s = total(clip(sessions, inp.start, inp.end))
        busy_s = total(clip(sessions + work, inp.start, inp.end))
        work_s = busy_s - session_s
        idle_s = max(0.0, window - busy_s)
        lines += ["| Share | Hours | Percent |", "|---|---|---|",
                  f"| Armed session (to its close or refusal item) | {_h(session_s)} | {100 * session_s / window:.0f}% |",
                  f"| Other magistrate work (smoke, Part A, dry runs) | {_h(work_s)} | {100 * work_s / window:.0f}% |",
                  f"| Idle or waiting | {_h(idle_s)} | {100 * idle_s / window:.0f}% |", ""]
        sinks.append((idle_s, "MBP idle or waiting"))
        summary.append(f"MBP: session {100 * session_s / window:.0f}%, other work {100 * work_s / window:.0f}%, "
                       f"idle {100 * idle_s / window:.0f}%")
        window_gaps = [g for g in gaps if inp.start <= g[0].stamp <= inp.end]
        if window_gaps:
            lines += ["Session close to next launch:", "",
                      "| Ended by item | Next arm item | Gap h | Budget h | Over 1.5x |", "|---|---|---|---|---|"]
            for end_item, nxt, gap, changed in window_gaps:
                budget = budgets.BUDGETS_S["session-gap-code" if changed else "session-gap"]
                over = gap > budgets.ALARM_FACTOR * budget
                lines.append(f"| {end_item.label} | {nxt.label if nxt else '(none yet)'} | {_h(gap)} | "
                             f"{_h(budget)} | {'yes' if over else 'no'} |")
                if over:
                    sinks.append((gap - budget, f"session gap after item {end_item.label} (excess over budget)"))
            lines.append("")

    # Top sinks
    lines += ["## Top five sinks", ""]
    for hours_s, label in sorted(sinks, key=lambda s: -s[0])[:5]:
        lines.append(f"1. {label}: {_h(hours_s)} h")
    if not sinks:
        lines.append("Nothing measured.")
    lines += ["", "Class (c) items (frozen or pinned code) go to the research lead with the measured saving (RL-127 term 11).", ""]
    top = sorted(sinks, key=lambda s: -s[0])[:3]
    summary.append("top sinks: " + "; ".join(f"{label} {_h(h)} h" for h, label in top) if top else "top sinks: none")
    return "\n".join(lines), summary
