    def test_changing_any_module_constant_changes_the_value_read_from_it(self) -> None:
        tool = self.tool
        python_refs = {tool.python_key(ref): ref for ref in self.refs if ref.kind == "python"}
        self.assertGreater(len(python_refs), 100)
        with tempfile.TemporaryDirectory(prefix="paper-b-registered-values-") as scratch_name:
            scratch = Path(scratch_name).resolve()
            ignore = shutil.ignore_patterns("__pycache__", "*.pyc")
            for package in ("joulewise", "scripts"):
                shutil.copytree(REPO_ROOT / package, scratch / package, ignore=ignore)
            # Read-only inputs are linked, never copied or written: only the two copied packages are changed.
            os.symlink(REPO_ROOT / "configs", scratch / "configs")

            unchanged = tool.read_python_constants(scratch, list(python_refs.values()))
            self.assertEqual(unchanged, {key: self.python_values[key] for key in python_refs},
                             "the scratch copy does not give the repository's values")

            def rewrite(relative: str, refs: list[Any]) -> None:
                source = (REPO_ROOT / relative).read_bytes()
                spans = sorted(((python_value_span(source, ref.symbol, ref.pointer), ref) for ref in refs),
                               key=lambda item: item[0][0], reverse=True)
                for index in range(len(spans) - 1):
                    self.assertGreaterEqual(spans[index][0][0], spans[index + 1][0][1],
                                            f"{relative}: two entries read overlapping expressions")
                for (start, end), ref in spans:
                    replacement = python_changed_expression(source[start:end],
                                                            self.python_values[tool.python_key(ref)])
                    source = source[:start] + replacement + source[end:]
                (scratch / relative).write_bytes(source)

            def restore(relative: str) -> None:
                shutil.copyfile(REPO_ROOT / relative, scratch / relative)

            by_file: dict[str, list[Any]] = {}
            for ref in python_refs.values():
                by_file.setdefault(ref.file, []).append(ref)

            # One run with every constant changed at once.
            for relative, refs in by_file.items():
                rewrite(relative, refs)
            together = tool.read_python_constants(scratch, list(python_refs.values()))
            for relative in by_file:
                restore(relative)
            # A constant computed from another one could, in principle, have had the two changes cancel:
            # any such constant is changed again on its own.
            alone = [key for key in python_refs if tool.same_value(together[key], self.python_values[key])]
            for key in alone:
                ref = python_refs[key]
                rewrite(ref.file, [ref])
                together[key] = tool.read_python_constants(scratch, [ref])[key]
                restore(ref.file)
            for key, ref in python_refs.items():
                with self.subTest(file=ref.file, key=ref.key):
                    self.assertFalse(tool.same_value(together[key], self.python_values[key]),
                                     f"still {self.python_values[key]!r}")

            # End to end through the command line: one constant changed, the committed table refused.
            before = subprocess.run([sys.executable, "-B", str(TOOL_PATH), "--root", str(scratch), "--check",
                                     "--against", str(self.committed_path)], capture_output=True, text=True,
                                    cwd=str(scratch), timeout=300, check=False)
            self.assertEqual(before.returncode, 0, before.stderr)
            settle = next(entry.ref for entry in self.entries if entry.id == "chain.settle_s")
            rewrite(settle.file, [settle])
            after = subprocess.run([sys.executable, "-B", str(TOOL_PATH), "--root", str(scratch), "--check",
                                    "--against", str(self.committed_path)], capture_output=True, text=True,
                                   cwd=str(scratch), timeout=300, check=False)
            self.assertEqual(after.returncode, 1, after.stderr)
            self.assertIn("chain.settle_s: value 60 in the committed file, 61 now", after.stderr)
            # The settle also feeds the post-capture reserve and disagrees with the sizing output's copy.
            self.assertIn("chain.horizon.post_reserve_s: value 1430 in the committed file, 1431 now", after.stderr)
            self.assertIn("DISAGREEMENT chain.settle_s", after.stderr)
            self.assertFalse((scratch / tool.OUTPUT_RELATIVE).exists(), "--check must not write the table")

