    def test_expected_chain_length_is_a_third_of_the_window_deadline_or_less(self) -> None:
        # The window deadline is a stop limit and the programmed span a worst case.  The glossary and the
        # deadline entries say in words that a chain is expected to take a third of the deadline or less; a
        # paper section that took the deadline for a window's length would describe about one window a day.
        # This keeps those words true of the numbers the table holds.
        values = {key: record["value"] for key, record in self.document["values"].items()}
        for label in self.tool.PACK_LABELS:
            with self.subTest(pack=label):
                pack = f"pack.{label}"
                slower = values[f"{pack}.expected_chain_s.measured_basis"]
                faster = values[f"{pack}.expected_chain_s.projected"]
                for figure in (slower, faster):
                    self.assertIs(type(figure), int)
                self.assertLess(0, faster)
                self.assertLess(faster, slower)
                self.assertLess(slower, values[f"{pack}.programmed_span_s"])
                self.assertLessEqual(3 * slower, values[f"{pack}.window_max_s"])
                for entry in (f"{pack}.window_max_s", f"{pack}.programmed_span_s"):
                    what = self.document["values"][entry]["what"]
                    self.assertIn(f"{pack}.expected_chain_s.measured_basis", what)
                    self.assertIn(f"{pack}.expected_chain_s.projected", what)

    # ---------------------------------------------------------------- counterfactuals: sources held in memory

    def _overlay_for(self, ref: Any) -> dict[str, bytes]:
        """Replacement bytes that change the one source value ``ref`` reads."""

        tool = self.tool
        if ref.kind == "json":
            document = copy.deepcopy(self.sources.json(ref.file))
            set_at(document, ref.pointer, changed(get_at(document, ref.pointer)))
            return {ref.file: dump(document)}
        if ref.kind == "markdown-json":
            text = self.sources.text(ref.file)
            start, end = tool.fenced_json_span(text, ref.heading, where=ref.file)
            block = json.loads(text[start:end])
            set_at(block, ref.pointer, changed(get_at(block, ref.pointer)))
            return {ref.file: (text[:start] + json.dumps(block, indent=2) + "\n" + text[end:]).encode("utf-8")}
        if ref.kind == "markdown-line":
            text = self.sources.text(ref.file)
            self.assertEqual(text.count("Status: **"), 1)
            return {ref.file: text.replace("Status: **", "Status: **~", 1).encode("utf-8")}
        if ref.kind == "markdown-table":
            text = self.sources.text(ref.file)
            start, end = tool.table_number_span(text, *ref.args, where=ref.file)
            number = int(text[start:end].replace(",", ""))
            return {ref.file: (text[:start] + str(number + 1) + text[end:]).encode("utf-8")}
        if ref.kind == "config-set":
            configurations = tool.member_configurations(self.sources, ref.dirs, ref.where)
            self.assertTrue(configurations, ref.key)
            if ref.rule == "count":
                return {f"{ref.dirs[0]}/~probe.json": dump(configurations[0][1])}
            overlay = {}
            for relative, original in configurations:     # change every configuration alike: the value moves
                document = copy.deepcopy(original)
                set_at(document, ref.pointer, changed(get_at(document, ref.pointer)))
                overlay[relative] = dump(document)
            return overlay
        self.assertEqual(ref.kind, "derived")
        document = copy.deepcopy(self.sources.json(ref.file))
        args = ref.args
        pointer = tool.pointer_tokens(args[0])
        if ref.rule == "count":
            container = get_at(document, pointer)
            add_member(container, copy.deepcopy(container[-1]) if isinstance(container, list) else {})
        elif ref.rule in {"count_where", "keys_where"}:
            add_member(get_at(document, pointer), {args[1]: args[2]})
        elif ref.rule == "count_where2":
            add_member(get_at(document, pointer), {args[1]: args[2], args[3]: args[4]})
        elif ref.rule == "distinct":
            add_member(get_at(document, pointer), {args[1]: "~probe"})
        elif ref.rule == "sum_where":
            add_member(get_at(document, pointer), {args[2]: args[3], args[1]: 1})
        elif ref.rule == "sum_nested":
            add_member(get_at(document, pointer), {args[1]: {args[2]: 1}})
        elif ref.rule == "value_or_zero":
            parent = get_at(document, pointer[:-1])
            parent[pointer[-1]] = parent.get(pointer[-1], 0) + 1
        elif ref.rule == "common":
            container = get_at(document, pointer)
            first = container[0] if isinstance(container, list) else next(iter(container.values()))
            sub = tool.pointer_tokens(args[1])
            set_at(first, sub, changed(get_at(first, sub)))
        elif ref.rule == "stage_rows":
            first = get_at(document, pointer)[0]
            first["stage_id"] = changed(first["stage_id"])
        elif ref.rule == "first_sentence":
            set_at(document, pointer, "~" + get_at(document, pointer))
        else:
            self.fail(f"no counterfactual defined for rule {ref.rule!r}")
        return {ref.file: dump(document)}

    def _resolve_with(self, ref: Any, overlay: dict[str, bytes]) -> Any:
        sources = self.tool.Sources(self.tool.Tree(REPO_ROOT, overlay), parent=self.sources)
        return self.tool.resolve(ref, sources, self.python_values)

    def test_changing_any_file_source_changes_the_value_read_from_it(self) -> None:
        seen = set()
        for ref in self.refs:
            if ref.kind == "python" or (ref.kind, ref.file, ref.key) in seen:
                continue
            seen.add((ref.kind, ref.file, ref.key))
            with self.subTest(file=ref.file, key=ref.key):
                before = self.tool.resolve(ref, self.sources, self.python_values)
                try:
                    after = self._resolve_with(ref, self._overlay_for(ref))
                except self.tool.ExtractionError:
                    continue        # the extraction fails: nothing would be written
                self.assertFalse(self.tool.same_value(before, after), f"still {before!r}")
        self.assertGreater(len(seen), 250)

