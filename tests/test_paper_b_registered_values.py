REPO_ROOT = Path(__file__).resolve().parents[1]
TOOL_PATH = REPO_ROOT / "docs" / "paper" / "tools" / "extract_registered_values.py"
ID_RE = re.compile(r"^[a-z0-9_]+(\.[A-Za-z0-9_-]+)+$")
# Project shorthand that must not reach text a paper author may copy (the paper brief's list, and kin).
SHORTHAND = (r"\bD-\d", r"\bint5\b", r"H_claim", r"[Mm]agistrate", r"[Cc]old pass", r"PLAN2", r"gate-prune",
             r"\blane\b", r"\bG10\b", r"\bR3\b", r"\bALPHA-\d", r"#4\d\d", r"\bNEG-?8 (screen|bound)\b")


def load_tool() -> Any:
    name = "paper_b_extract_registered_values"
    spec = importlib.util.spec_from_file_location(name, TOOL_PATH)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module      # dataclasses look their module up while the class body runs
    spec.loader.exec_module(module)
    return module


def changed(value: Any) -> Any:
    """A value of the same kind that differs from ``value``."""

    if isinstance(value, bool):
        return not value
    if isinstance(value, (int, float)):
        return value + 1
    if isinstance(value, str):
        return value + "~"
    if value is None:
        return 1
    if isinstance(value, list):
        return value + ["~"]
    if isinstance(value, dict):
        return {**value, "~": 1}
    raise AssertionError(f"no change defined for {type(value).__name__}")


def set_at(document: Any, tokens: tuple, value: Any) -> None:
    node = document
    for token in tokens[:-1]:
        node = node[int(token)] if isinstance(node, list) else node[token]
    last = tokens[-1]
    if isinstance(node, list):
        node[int(last)] = value
    else:
        node[last] = value


def get_at(document: Any, tokens: tuple) -> Any:
    node = document
    for token in tokens:
        node = node[int(token)] if isinstance(node, list) else node[token]
    return node


def add_member(container: Any, member: Any) -> None:
    if isinstance(container, list):
        container.append(member)
    else:
        container["~probe"] = member


def dump(document: Any) -> bytes:
    return (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def python_value_span(source: bytes, symbol: str, path: tuple) -> tuple[int, int]:
    """Byte span of the expression that gives ``symbol[path...]`` its value at module level."""

    node: ast.expr | None = None
    for statement in ast.parse(source).body:
        if isinstance(statement, ast.Assign):
            for target in statement.targets:
                if isinstance(target, ast.Name) and target.id == symbol:
                    node = statement.value
                elif isinstance(target, ast.Tuple) and isinstance(statement.value, ast.Tuple):
                    for name, value in zip(target.elts, statement.value.elts):
                        if isinstance(name, ast.Name) and name.id == symbol:
                            node = value
        elif (isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name)
              and statement.target.id == symbol and statement.value is not None):
            node = statement.value
    if node is None:
        raise LookupError(f"no module-level assignment to {symbol}")
    for step in path:
        if isinstance(node, ast.Dict):
            matches = [value for key, value in zip(node.keys, node.values)
                       if isinstance(key, ast.Constant) and key.value == step]
            if len(matches) != 1:
                raise LookupError(f"{symbol}: no literal key {step!r}")
            node = matches[0]
        elif isinstance(node, (ast.Tuple, ast.List)):
            node = node.elts[step]
        else:
            raise LookupError(f"{symbol}: {step!r} is below an expression that is not a literal container")
    starts = [0]
    for line in source.splitlines(keepends=True):
        starts.append(starts[-1] + len(line))
    return (starts[node.lineno - 1] + node.col_offset, starts[node.end_lineno - 1] + node.end_col_offset)


def python_changed_expression(expression: bytes, value: Any) -> bytes:
    """Source text of an expression that evaluates to something other than ``value``."""

    if isinstance(value, bool):
        return b"(not (" + expression + b"))"
    if isinstance(value, (int, float)):
        return b"((" + expression + b") + 1)"
    if isinstance(value, str):
        return b'((' + expression + b') + "~")'
    if value is None:
        return b"(1)"
    if isinstance(value, list):
        return b'((lambda item: type(item)(list(item) + ["~"]))(' + expression + b"))"
    raise AssertionError(f"no change defined for a module constant of type {type(value).__name__}")


class RegisteredValuesTests(unittest.TestCase):
    maxDiff = None

    @classmethod
    def setUpClass(cls) -> None:
        cls.tool = load_tool()
        cls.entries = cls.tool.manifest()
        cls.refs = cls.tool.all_refs(cls.entries)
        cls.python_values = cls.tool.read_python_constants(REPO_ROOT, cls.refs)
        cls.tree = cls.tool.Tree(REPO_ROOT)
        cls.sources = cls.tool.Sources(cls.tree)
        cls.document = cls.tool.build_document(cls.tree, cls.python_values, cls.entries)
        cls.rendered = cls.tool.render(cls.document)
        cls.committed_path = REPO_ROOT / cls.tool.OUTPUT_RELATIVE
        cls.committed = cls.committed_path.read_bytes()

    # ---------------------------------------------------------------- the acceptance test

    def test_committed_table_is_what_the_sources_give_now(self) -> None:
        if self.rendered != self.committed:
            lines = self.tool.describe_difference(self.committed, self.rendered)
            self.fail("docs/paper/paper-b/registered-values.json no longer matches its sources. This is expected "
                      "on a commit that revises or seals the registration, the sizing output, the identity pins "
                      "or the sealed inventory: regenerate the table "
                      "(python3 -B docs/paper/tools/extract_registered_values.py --write), commit it in the same "
                      "pull request, and re-sync the paper text that cites these entries:\n  " + "\n  ".join(lines))

    def test_command_line_check_passes_on_the_committed_table(self) -> None:
        completed = subprocess.run([sys.executable, "-B", str(TOOL_PATH), "--check"], capture_output=True,
                                   text=True, cwd=str(REPO_ROOT), timeout=300, check=False)
        self.assertEqual(completed.returncode, 0, completed.stderr)

    # ---------------------------------------------------------------- shape of the table

    def test_every_entry_names_a_file_and_a_key(self) -> None:
        committed = json.loads(self.committed)
        self.assertEqual(committed["schema"], self.tool.SCHEMA)
        self.assertGreater(len(committed["values"]), 400)
        self.assertEqual(list(committed["values"]), sorted(committed["values"]))
        kinds = {"json", "markdown-json", "markdown-line", "markdown-table", "python", "derived", "config-set"}
        for entry_id, record in committed["values"].items():
            with self.subTest(entry=entry_id):
                self.assertRegex(entry_id, ID_RE)
                self.assertEqual(set(record) - {"also"}, {"value", "unit", "what", "source"})
                self.assertIn(record["unit"], self.tool.UNITS)
                self.assertTrue(record["what"].strip().endswith("."), record["what"])
                for place in [record["source"], *record.get("also", [])]:
                    self.assertIn(place["kind"], kinds)
                    self.assertTrue(place["key"].strip())
                    for path in place["file"].split("; "):
                        self.assertFalse(Path(path).is_absolute() or ".." in Path(path).parts, path)
                        self.assertTrue((REPO_ROOT / path).exists(), f"{path} does not exist")
                for place in record.get("also", []):
                    self.assertIn("value", place)

    def test_sources_are_design_files_only(self) -> None:
        # Committed configuration and code: never a runs directory, an archive or a harvest output.
        sources = json.loads(self.committed)["sources"]
        self.assertGreater(len(sources), 20)
        for source in sources:
            with self.subTest(source=source["file"]):
                self.assertIn(Path(source["file"]).parts[0], {"configs", "joulewise", "scripts"})
                self.assertTrue((REPO_ROOT / source["file"]).exists())

    def test_no_two_places_that_state_one_quantity_disagree(self) -> None:
        self.assertEqual(self.document["disagreements"], [])
        for entry_id, record in self.document["values"].items():
            for place in record.get("also", []):
                with self.subTest(entry=entry_id, also=place["key"]):
                    self.assertTrue(self.tool.same_value(record["value"], place["value"]))

    def test_descriptions_carry_no_project_shorthand(self) -> None:
        texts = {f"values.{key}": record["what"] for key, record in self.document["values"].items()}
        for where, text in texts.items():       # the label is glossed once, in the glossary, and used nowhere else
            with self.subTest(where=where, pattern="NEG-8"):
                self.assertNotIn("NEG-8", text)
        texts.update({f"glossary.{item['term']}": item["meaning"] for item in self.document["glossary"]})
        for where, text in texts.items():
            for pattern in SHORTHAND:
                with self.subTest(where=where, pattern=pattern):
                    self.assertIsNone(re.search(pattern, text), text)

