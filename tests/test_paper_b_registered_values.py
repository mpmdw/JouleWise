"""Paper B's registered-values table equals what the extractor reads from the sources now.

``docs/paper/paper-b/registered-values.json`` is generated by
``docs/paper/tools/extract_registered_values.py``.  These tests:

* regenerate the table and compare bytes with the committed file;
* check that every entry names a file and a key, and that no two committed
  places that state one quantity disagree;
* change each source value in turn and require the entry read from it to
  change (or the extraction to fail), so that the file and key an entry
  names are proven to be where its value comes from.  JSON, Markdown and
  member-configuration sources are changed in memory; module constants are
  changed in a scratch copy of ``joulewise/`` and ``scripts/`` under TMPDIR,
  which the extractor's child interpreter imports;
* check that the table covers every key of the blocks and tables it reads
  (a threshold or budget added later cannot be missing from it silently).

Nothing here reads a bundle, an energy or a harvest output.
"""

