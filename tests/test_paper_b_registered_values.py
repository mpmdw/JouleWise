    def test_each_description_stands_alone(self) -> None:
        # Entries are sorted by id and cited one at a time, so a description may not lean on its neighbour.
        leaning = (r"\b[Tt]hat (fraction|charge|value|size|bound|test|block|diagnostic|reproduction|power)\b",
                   r"\bsuch run\b", r"\bsame (decision|way|parts)\b", r"\bversions below\b", r"\bblock[- ]5\b",
                   r"\bdisclosed\b")
        for key, record in self.document["values"].items():
            for pattern in leaning:
                with self.subTest(entry=key, pattern=pattern):
                    self.assertIsNone(re.search(pattern, record["what"]), record["what"])
        # A description that points at another entry names one that exists.
        ids = set(self.document["values"])
        prefixes = sorted({key.split(".")[0] for key in ids})
        pointer = re.compile(r"\b(?:" + "|".join(prefixes) + r")\.[A-Za-z0-9_.*-]*[A-Za-z0-9_*]")
        for key, record in self.document["values"].items():
            for named in pointer.findall(record["what"]):
                with self.subTest(entry=key, names=named):
                    if named.endswith(".*"):
                        self.assertTrue(any(other.startswith(named[:-1]) for other in ids))
                    else:
                        self.assertIn(named, ids)

