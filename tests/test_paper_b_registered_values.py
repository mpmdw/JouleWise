    def test_table_number_needs_one_table_one_row_and_a_number_with_its_unit(self) -> None:
        tool = self.tool
        text = ("intro\n\n"
                "  | Pack | Deadline | Expected chain |\n"
                "  |---|---|---|\n"
                "  | ALPHA | 102,180 s (28.4 h) | 19,460 s (5.4 h) |\n"
                "  | BETA | 104580 s | about 5.7 h |\n"
                "\n"
                "| Pack | Other |\n|---|---|\n| ALPHA | 7 s |\n")
        self.assertEqual(tool.table_number(text, "Expected chain", "ALPHA", "s", where="t"), 19460)
        self.assertEqual(tool.table_number(text, "Deadline", "ALPHA", "s", where="t"), 102180)
        self.assertEqual(tool.table_number(text, "Deadline", "BETA", "s", where="t"), 104580)
        self.assertEqual(tool.table_number(text, "Other", "ALPHA", "s", where="t"), 7)
        start, end = tool.table_number_span(text, "Expected chain", "ALPHA", "s", where="t")
        self.assertEqual(text[start:end], "19,460")
        refused = (
            (text, "Absent", "ALPHA", "s"),                 # no table has the column
            (text, "Pack", "ALPHA", "s"),                   # two tables have the column
            (text, "Expected chain", "GAMMA", "s"),         # no such row
            (text, "Expected chain", "BETA", "s"),          # the cell does not open with a number
            (text, "Expected chain", "ALPHA", "h"),         # the number is in another unit
            (text.replace("19,460 s (5.4 h)", "19,460 sec"), "Expected chain", "ALPHA", "s"),  # the unit is whole
            (text.replace("| BETA | 104580 s |", "| ALPHA | 104580 s |"), "Deadline", "ALPHA", "s"),   # two rows
            (text.replace("19,460 s", "19,46 s"), "Expected chain", "ALPHA", "s"),     # digits not in threes
            (text.replace(" | 19,460 s (5.4 h) |", " |"), "Deadline", "ALPHA", "s"),   # a row short of a cell
        )
        for case in refused:
            with self.subTest(column=case[1], row=case[2], unit=case[3]):
                with self.assertRaises(tool.ExtractionError):
                    tool.table_number(*case, where="t")


