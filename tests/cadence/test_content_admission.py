PROTECTED = ("power_trace.csv", "rich_telemetry.jsonl", "powermetrics.plist")


def protected(names):
    return [name for name in names if "/hazards/meter/" in name or Path(name).name in PROTECTED]


class _Copy(unittest.TestCase):
    """A private copy of the generated custody, its pin list and a RUN_STATE the pins chain to."""

    def setUp(self):
        shared = TLR._Custody.get()
        tmp = tempfile.TemporaryDirectory(prefix="content-admission-")
        self.addCleanup(tmp.cleanup)
        self.tmp = Path(tmp.name)
        self.root = self.tmp / "custody"
        shutil.copytree(shared.root, self.root)
        self.roster, self.rules = self.root / "roster.json", self.root / "rules_3_4.json"
        self.ids = [span["span_id"] for span in json.loads(self.roster.read_bytes())]
        self.doc = PF.synthetic_pins({sid: self.root / sid for sid in self.ids})
        self.pins = self.tmp / "custody_pins.json"
        self.pins.write_bytes(PF.dump(self.doc))
        self.run_state = self.tmp / "RUN_STATE.md"
        self.run_state.write_text(PF.run_state(self.doc), encoding="utf-8")
        self.span = self.root / self.ids[0]
        self.trace = sorted(self.span.glob("legs/*/runtime/runs/cadence-leg/power_trace.csv"))[0]
        self.stream = sorted(self.span.glob("hazards/meter/stream-*.jsonl"))[0]
        self.receipt = self.span / "runner_receipt.json"

    def faults(self):
        """Each fault leaves the custody other than its pins; the callable returned by ``apply`` undoes it."""
        def changed(path):
            def apply():
                data = path.read_bytes()
                path.write_bytes(bytes([data[0] ^ 1]) + data[1:])
                return lambda: path.write_bytes(data)
            return apply

        def missing():
            data = self.stream.read_bytes()
            self.stream.unlink()
            return lambda: self.stream.write_bytes(data)

        def extra():
            added = self.stream.with_name("stream-9999.jsonl")
            added.write_bytes(b"{}\n")
            return added.unlink

        def substituted():
            other = sorted(self.span.glob("legs/*/runtime/runs/cadence-leg/power_trace.csv"))[1]
            a, b = self.trace.read_bytes(), other.read_bytes()
            self.trace.write_bytes(b)
            other.write_bytes(a)
            return lambda: (self.trace.write_bytes(a), other.write_bytes(b))

        def symlink():
            kept = self.tmp / "kept-trace.csv"
            shutil.move(self.trace, kept)
            self.trace.symlink_to(kept)                # it resolves to the very bytes that are pinned
            return lambda: (self.trace.unlink(), shutil.move(kept, self.trace))
        rel = lambda path: f"{self.ids[0]}/{path.relative_to(self.span).as_posix()}"
        return {
            "a changed trace": (changed(self.trace), rel(self.trace) + ": its bytes are not its pin"),
            "a changed receipt": (changed(self.receipt), rel(self.receipt) + ": its bytes are not its pin"),
            "a missing stream": (missing, rel(self.stream) + ": a pinned file is missing"),
            "an extra stream": (extra, "stream-9999.jsonl: a file that is not pinned"),
            "a substituted trace": (substituted, "its bytes are not its pin"),
            "a symlinked trace": (symlink, rel(self.trace) + ": a symlink"),
        }


@unittest.skipIf(R is None, "numpy is not installed")
class Stage1(_Copy):
    def stage1(self, *extra, pins=None):
        out = self.tmp / f"stage1-{len(list(self.tmp.iterdir()))}.json"
        rc, _, err = TLR.run_cli(["stage1", "--roster", self.roster, "--custody", self.root, "--rules-3-4", self.rules,
                                  "--out", out, "--custody-pins", pins or self.pins, *extra])
        return rc, err, out

    def test_the_pinned_custody_is_admitted_and_chained_to_its_checks(self):
        rc, err, out = self.stage1("--run-state", self.run_state)
        self.assertEqual(rc, 0, err)
        # stage 1's output carries nothing of the pin list: it must not vary with the bytes of an energy file
        recorded = json.loads(out.read_bytes())["code_sha256"]
        self.assertEqual(sorted(key for key in recorded if key.startswith("input:")),
                         ["input:roster_sha256", "input:rules_3_4_sha256"])
        served = TLR.LAST_RUN["served"]
        self.assertIn(f"{self.ids[0]}/runner_receipt.json", served)          # the stage parsed the verified bytes
        self.assertTrue(protected(served))                                   # the time fields of the energy files too

    def test_a_file_that_is_not_its_pin_refuses_before_any_roster_file_is_parsed(self):
        for label, (apply, message) in self.faults().items():
            undo = apply()
            try:
                rc, err, out = self.stage1()
            finally:
                undo()
            with self.subTest(label):
                self.assertEqual(rc, 2, err)
                self.assertIn("REFUSED custody pins: ", err)       # (a stage may print a warning line first)
                self.assertIn(message, err)
                self.assertFalse(out.exists())
                self.assertEqual(TLR.LAST_RUN["served"], [])                 # no other read: nothing was parsed

    def test_a_pin_not_chained_to_its_check_refuses(self):
        digest = self.doc["spans"][0]["offload_manifest_sha256"]
        other = self.tmp / "RUN_STATE-other.md"
        other.write_text(self.run_state.read_text().replace(digest, "0" * 64), encoding="utf-8")
        rc, err, out = self.stage1("--run-state", other)
        self.assertEqual(rc, 2, err)
        self.assertIn(f"custody pins: {self.ids[0]}: Check item", err)
        self.assertIn("does not name its offload manifest's sha256", err)
        self.assertEqual(TLR.LAST_RUN["served"], [])

        # a pin changed together with its file: the custody would match the pins, but the pins no longer rebuild
        # the offload manifest the span carries, so they do not chain to the Check that names it
        data = self.trace.read_bytes()
        self.trace.write_bytes(data + b"\n")
        changed = json.loads(json.dumps(self.doc))
        entry = next(e for e in changed["spans"][0]["files"]
                     if e["path"] == self.trace.relative_to(self.span).as_posix())
        entry.update(sha256=hashlib.sha256(data + b"\n").hexdigest(), size=len(data) + 1)
        forged = self.tmp / "forged-pins.json"
        forged.write_bytes(PF.dump(changed))
        try:
            rc, err, out = self.stage1(pins=forged)
        finally:
            self.trace.write_bytes(data)
        self.assertEqual(rc, 2, err)
        self.assertIn("not the lines of the offload manifest it names", err)
        self.assertFalse(out.exists())
        self.assertEqual(TLR.LAST_RUN["served"], [])

    def test_the_pins_name_exactly_the_roster_s_spans(self):
        fewer = self.tmp / "fewer-pins.json"
        fewer.write_bytes(PF.dump(dict(self.doc, spans=self.doc["spans"][1:])))
        rc, err, out = self.stage1(pins=fewer)
        self.assertEqual(rc, 2, err)
        self.assertIn("custody pins: the pin list names", err)
        self.assertFalse(out.exists())

    def test_only_a_draft_run_may_name_its_own_pin_list_or_run_state(self):
        for flags, text in (({"custody_pins": str(self.pins), "run_state": None}, "--custody-pins"),
                            ({"custody_pins": None, "run_state": str(self.run_state)}, "--run-state")):
            a = argparse.Namespace(allow_draft=False, **flags)
            pinned = (json.loads(json.dumps(self.doc)), "0" * 64)
            with self.subTest(text), unittest.mock.patch.object(R, "_VERIFIED", [({}, None)]), \
                    unittest.mock.patch.object(R.M, "input_pins", return_value=pinned), \
                    contextlib.ExitStack() as stack, self.assertRaisesRegex(F.LookInputError, text):
                R.admit_custody(a, self.ids, R.span_dirs(self.root, None), stack)

    def test_the_bytes_parsed_are_the_bytes_hashed(self):
        """After the first act a roster file is never read from disk again. Another process rewrites a trace, a stream
        and a receipt once the check has passed; level R is what it is for the pinned bytes."""
        roster, rules = json.loads(self.roster.read_bytes()), json.loads(self.rules.read_bytes())
        sdir_of = R.span_dirs(self.root, None)
        expected = F.dump(R.read_look_input(roster, sdir_of, rules))
        a = argparse.Namespace(allow_draft=True, custody_pins=str(self.pins), run_state=None)
        rewrite = "import sys\nfor p in sys.argv[1:]:\n    open(p, 'wb').write(b'rewritten after the check\\n')\n"
        with unittest.mock.patch.object(R, "_VERIFIED", [({}, None)]), contextlib.ExitStack() as stack:
            custody, _ = R.admit_custody(a, self.ids, sdir_of, stack)
            subprocess.run([sys.executable, "-c", rewrite, self.trace, self.stream, self.receipt], check=True)
            got = F.dump(R.read_look_input(roster, sdir_of, rules))
            self.assertTrue(protected(f"{sid}/{rel}" for sid, rel in custody.opened))
        self.assertEqual(got, expected)
        self.assertEqual(self.trace.read_bytes(), b"rewritten after the check\n")     # the disk did change


@unittest.skipIf(R is None, "numpy is not installed")
class Stage2(_Copy):
    def setUp(self):
        super().setUp()
        self.stage1 = self.tmp / "stage1.json"
        rc, _, err = TLR.run_cli(["stage1", "--roster", self.roster, "--custody", self.root, "--rules-3-4", self.rules,
                                  "--out", self.stage1, "--custody-pins", self.pins])
        self.assertEqual(rc, 0, err)

    def test_stage_2_refuses_a_file_that_is_not_its_pin_before_the_reservation(self):
        """Stage 2's first act on custody is the same check. It consumes nothing: no reservation is attempted, no
        twin is launched and no roster file is parsed."""
        faults = self.faults()
        for label in ("a changed trace", "a missing stream", "an extra stream", "a symlinked trace"):
            apply, message = faults[label]
            undo = apply()
            out = self.tmp / "fit.json"
            try:
                rc, _, err = TLR.run_cli(
                    ["stage2", "--stage1", self.stage1, "--stage1-sha256", R.sha256_file(self.stage1),
                     "--custody", self.root, "--out", out, "--custody-pins", self.pins],
                    extra={"twin_path": "no-twin-is-launched"})
            finally:
                undo()
            with self.subTest(label):
                self.assertEqual(rc, 2, err)
                self.assertIn("REFUSED custody pins: ", err)       # (a stage may print a warning line first)
                self.assertIn(message, err)
                self.assertEqual((TLR.LAST_RUN["reservation_attempts"], TLR.LAST_RUN["twin_launches"]), (0, 0))
                self.assertEqual(TLR.LAST_RUN["served"], [])
                self.assertFalse(out.exists())
                self.assertFalse(any(Path(dirpath).name == "RESTRICTED" for dirpath, _, _ in os.walk(self.tmp)))


if __name__ == "__main__":
    unittest.main()
