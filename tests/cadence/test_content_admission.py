"""RL-194 at the look's command line: stage 1 and stage 2 admit custody by content address before anything else.

Every byte is generated by scripts/cadence_look_synth.py; no custody, energy, meter or restricted file of a real run
is read. The pin list of a generated custody is made from its bytes as generated (a real one never is: its digests
are the lines of each span's offload manifest), and every refusal below is then made by changing the custody, or the
pins, afterwards.
"""
