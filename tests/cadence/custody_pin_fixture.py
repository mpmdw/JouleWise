"""Pin lists for generated custody (RL-194). A real pin list is never made this way: its digests are the lines of each
span's offload manifest. Here the bytes are generated by the test, so they are hashed as they stand."""
from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path

from joulewise.cadence_looks import custody_pins


def quiet_bytes(path):
    """A file's bytes read below ``open``: a test that spies on ``builtins.open``, ``io.open`` and ``os.open`` to see
    what a stage reads does not see the fixture making the pin list."""
    with io.FileIO(str(path), "r") as handle:
        return handle.readall()


def synthetic_pins(span_dirs):
    """A pin list in the real list's shape for ``{span id: directory}``: a SHA256SUMS per span in path order."""
    spans = []
    for index, (sid, root) in enumerate(sorted(span_dirs.items())):
        root = Path(root)
        files = {path.relative_to(root).as_posix(): quiet_bytes(path)
                 for path in sorted(root.rglob("*")) if path.is_file()}
        sums = "".join(f"{hashlib.sha256(data).hexdigest()}  ./{name}\n" for name, data in files.items()).encode()
        spans.append(custody_pins.span_pins(sid, sums, {name: len(data) for name, data in files.items()},
                                            runner_commit="0" * 40, close_item=2 * index + 2, check_item=2 * index + 1))
    return {"schema": custody_pins.SCHEMA, "spans": spans}


def placeholder_pins():
    """A filled, internally chained pin list that names no span of any test's roster: for a committed manifest in a
    test that opens no custody."""
    sums = b"0" * 64 + b"  ./runner_receipt.json\n"
    return {"schema": custody_pins.SCHEMA, "spans": [custody_pins.span_pins(
        "dev-00-s00", sums, {"runner_receipt.json": 0}, runner_commit="0" * 40, close_item=2, check_item=1)]}


def run_state(doc):
    """A RUN_STATE whose Check items name each span's offload manifest digest, newest item first."""
    items = [f"{span['check_item']}. **Check of {span['span_id']} (generated).** Offload manifest "
             f"`{span['offload_manifest_sha256']}` ({len(span['files'])} files).\n"
             for span in sorted(doc["spans"], key=lambda span: -span["check_item"])]
    return "# Generated run state\n\n" + "\n".join(items)


def dump(doc):
    return (json.dumps(doc, sort_keys=True, separators=(",", ":"), allow_nan=False) + "\n").encode()
