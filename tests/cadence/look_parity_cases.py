def provenance(r):
    """Round 1: the rehearsal verdict, bound through the official row CLI and moved into the campaign path."""
    fx = r.fx
    rules = fx.look / M.LOOK_FILES["rules_3_4"]
    rules.unlink()
    rows = M.load_json(fx.ledger)
    row = rows["looks"][0]
    doc = M.load_json(fx.manifest)
    doc["status"] = "draft"
    r.save(fx.manifest, doc)
    row.update(status="draft", sha256=M.sha256_file(fx.manifest))
    row.pop("verdicts_sha256")
    r.save(fx.ledger, rows)
    r.commit("Bind generated draft and host", M.REHEARSAL_BRANCH)
    MR.git(fx.repo, "checkout", "-q", "--detach")
    r.need(r.rehearse_rules(fx.rehearsal), "rehearsal producer")
    private = fx.rehearsal / rules.name
    row["verdicts_sha256"] = M.sha256_file(private)
    r.save(fx.ledger, rows)
    r.commit("Record draft rehearsal verdict", M.REHEARSAL_BRANCH)
    doc["status"] = "committed"
    r.save(fx.manifest, doc)
    row.update(status="committed", sha256=M.sha256_file(fx.manifest))
    row.pop("verdicts_sha256")
    r.save(fx.ledger, rows)
    r.commit("Register the committed fixture", "main")
    r.need(r.cli(MANIFEST_CLI, "row", "--repo", fx.repo, "--manifest", fx.manifest,
                 "--roster", fx.look / "roster.json", "--verdicts", private, "--write"), "row CLI")
    r.commit("Bind inputs from the stock row CLI", "main")
    r.control([lambda: r.cli(PRODUCER, *r.stock_args()), lambda: r.stage1()])
    rules.unlink()
    r.clear(fx.look, receipt=True)
    private.rename(rules)                    # the same rehearsal inode, with no stock run after the commit
    return r.act([lambda: r.stage1()])


def span_override_setup(r):
    """Round 2: the verdict hash is the rehearsal's on the retained span; the registered span has since changed."""
    fx = r.fx
    rules = fx.look / M.LOOK_FILES["rules_3_4"]
    rules.unlink()
    rows = M.load_json(fx.ledger)
    row = rows["looks"][0]
    doc = M.load_json(fx.manifest)
    doc["status"] = "draft"
    r.save(fx.manifest, doc)
    row.update(status="draft", sha256=M.sha256_file(fx.manifest))
    row.pop("verdicts_sha256")
    r.save(fx.ledger, rows)
    r.commit("Bind generated draft and host", M.REHEARSAL_BRANCH)
    MR.git(fx.repo, "checkout", "-q", "--detach")
    r.need(r.rehearse_rules(fx.rehearsal), "rehearsal producer")
    private = fx.rehearsal / rules.name
    row["verdicts_sha256"] = M.sha256_file(private)
    r.save(fx.ledger, rows)
    r.commit("Record draft rehearsal verdict", M.REHEARSAL_BRANCH)
    sid, leg = next(key.split("/") for key, verdict in M.load_json(private).items()
                    if verdict["sidecar_coverage"] and key.startswith("dev-"))
    span = fx.custody / sid
    retained = fx.scratch / "retained-draft-copy" / sid
    shutil.copytree(span, retained)
    bundle = M.runtime_bundle(span, leg, M.load_json(span / "legs" / leg / "leg_record.json"))
    changed = bundle / "rich_telemetry.jsonl"
    lines = changed.read_bytes().splitlines(keepends=True)
    assert len(lines) > 10
    changed.write_bytes(lines[0] + lines[-1])
    roster = M.load_json(fx.look / "roster.json")
    doc["inputs"]["pins"] = MR.write_pins(fx.repo, {entry["span_id"]: fx.custody / entry["span_id"] for entry in roster})
    doc["status"] = "committed"
    r.save(fx.manifest, doc)
    row.update(status="committed", sha256=M.sha256_file(fx.manifest))
    row.pop("verdicts_sha256")
    r.save(fx.ledger, rows)
    r.commit("Register the committed fixture", "main")
    r.need(r.cli(MANIFEST_CLI, "row", "--repo", fx.repo, "--manifest", fx.manifest,
                 "--roster", fx.look / "roster.json", "--verdicts", private, "--write"), "row CLI")
    r.commit("Bind inputs from the stock row CLI", "main")
    return sid, retained, changed, retained / changed.relative_to(span)


def span_override_flag(r):
    sid, retained, _, _ = span_override_setup(r)
    return r.act([lambda: r.cli(PRODUCER, *r.stock_args(), "--span-dir", f"{sid}={retained}"), lambda: r.stage1()])


def span_override_copy(r):
    _, _, changed, stale = span_override_setup(r)
    current = changed.read_bytes()
    assert stale.read_bytes() != current

    def stock_over_stale_copy():
        changed.write_bytes(stale.read_bytes())
        try:
            return r.cli(PRODUCER, *r.stock_args())
        finally:
            changed.write_bytes(current)        # the pinned input is back before stage 1 runs
    return r.act([stock_over_stale_copy, lambda: r.stage1()])


def bind_generated(r):
    """Commit the draft producer's verdict hash on main, as the round-2 and round-3 scripts do."""
    fx = r.fx
    generated = r.generate()
    rows = M.load_json(fx.ledger)
    rows["looks"][0]["verdicts_sha256"] = M.sha256_file(generated)
    r.save(fx.ledger, rows)
    MR.git_commit(fx.repo, "Commit generated verdict and execution host")
    return generated, rows


def preflight_fetch(r, checkpoint="run_verifier"):
    """Round 2: a fetch during campaign stage 1 changes the committed verdict hash."""
    fx = r.fx
    _, rows = bind_generated(r)
    r.control([lambda: r.cli(PRODUCER, *r.stock_args()), lambda: r.stage1()])
    r.clear(fx.look)
    other = r.second_checkout()
    rows["looks"][0]["verdicts_sha256"] = "e" * 64
    r.save(other / M.LOOK_LEDGER_PATH, rows)
    MR.git_commit(other, "Update verdict commitment from second checkout", publish=False)
    return r.act([lambda: r.stage1(advance=(checkpoint, str(other)))])


def preflight_fetch_publication(r):
    return preflight_fetch(r, "finish_stage1")


def seed_destination(r, target, generated):
    target.mkdir(mode=0o700, parents=True)
    rules = target / M.LOOK_FILES["rules_3_4"]
    rules.write_bytes(generated.read_bytes())
    rules.chmod(0o600)


def rehearsal_fetch(r, checkpoint="run_verifier"):
    """Round 3: a fetch during the rehearsal registers its destination as the campaign look directory."""
    fx = r.fx
    generated, rows = bind_generated(r)
    new_root = fx.scratch / "second-root"
    target = new_root / M.INTERIM_LOOK_ID
    seed_destination(r, target, generated)
    r.control([lambda: r.stage1("--rehearsal", target)])
    r.clear(target)
    other = r.second_checkout()
    for entry in M.load_json(fx.look / "roster.json"):
        shutil.copytree(fx.custody / entry["span_id"], new_root / entry["span_id"])
    moved = other / MR.MANIFEST
    doc = M.load_json(moved)
    doc["custody"]["root"] = str(new_root)
    r.save(moved, doc)
    rows["looks"][0].update(custody_root=str(new_root), sha256=M.sha256_file(moved))
    r.save(other / M.LOOK_LEDGER_PATH, rows)
    MR.git_commit(other, "Register the second synthetic custody root on main", publish=False)
    return r.act([lambda: r.stage1("--rehearsal", target, advance=(checkpoint, str(other)))], target)


def rehearsal_fetch_publication(r):
    return rehearsal_fetch(r, "finish_rehearsal")


def rehearsal_fence_branch(r):
    """The destination fence alone: the rehearsal reads its ledger from the shared branch; main registers the
    destination's parent as a custody root during the run."""
    fx = r.fx
    generated = r.generate()
    main = r.head()
    doc = M.load_json(fx.manifest)
    doc["status"] = "draft"
    r.save(fx.manifest, doc)
    rows = M.load_json(fx.ledger)
    rows["looks"][0].update(status="draft", sha256=M.sha256_file(fx.manifest),
                            verdicts_sha256=M.sha256_file(generated))
    r.save(fx.ledger, rows)
    r.commit("Register the input-bound branch draft", M.REHEARSAL_BRANCH)
    MR.git(fx.repo, "checkout", "-q", "--detach")
    main_root = fx.scratch / "main-root"
    target = main_root / M.INTERIM_LOOK_ID
    seed_destination(r, target, generated)
    r.control([lambda: r.stage1("--rehearsal", target)])
    r.clear(target)
    other = r.second_checkout(main)
    on_main = M.load_json(other / M.LOOK_LEDGER_PATH)
    on_main["looks"][0]["custody_root"] = str(main_root)
    r.save(other / M.LOOK_LEDGER_PATH, on_main)
    MR.git_commit(other, "Register the destination's parent as a custody root on main", publish=False)
    return r.act([lambda: r.stage1("--rehearsal", target, advance=("run_verifier", str(other)))], target)


CASES = {f.__name__: f for f in (provenance, span_override_flag, span_override_copy, preflight_fetch,
                                 preflight_fetch_publication, rehearsal_fetch, rehearsal_fetch_publication,
                                 rehearsal_fence_branch)}


def main():
    from tests.cadence import test_look_run

    case, report = sys.argv[2], Path(sys.argv[3])
    fx = Stage1Rehearsal()
    try:
        fx.setUp()
        replay = Replay(fx)
        act = CASES[case](replay)
        result = {"case": case, "controls": replay.controls, "act": act}
    finally:
        fx.doCleanups()
        shutil.rmtree(test_look_run._PIN_DIR, ignore_errors=True)    # the module's harness directory, made at import
    report.write_text(json.dumps(result, indent=1, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
