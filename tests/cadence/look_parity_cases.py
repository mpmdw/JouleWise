"""PR #971 convergence replays (lead spec S2): every audit reproducer of rounds 1 to 3, on generated custody.

Run as ``python -I -B tests/cadence/look_parity_cases.py TREE CASE REPORT``. TREE is the source tree under test:
this checkout, or the pre-fix parent 75ce4bf5c extracted from git. The script imports the fixture, the runner and
the producer from TREE only (``-I`` keeps this file's directory off ``sys.path``), so one replay runs unchanged
against both trees. It writes REPORT as JSON: each control's exit codes, then the case's act with its exit codes,
the last line of each step's output and every output file the act created, changed or removed.

The sources, all under /Volumes/JW-EXT/scratch (names only):

* ``provenance``: astra-971-audit-1125/tmp/provenance.py (round 1). A rehearsal-produced verdict moved into the
  campaign path, with no post-commit stock run.
* ``span_override_flag``, ``span_override_copy``: astra-971-narrow-1125/tmp/span_override.py (round 2). The stock
  producer reads a stale span through ``--span-dir``, or through a stale copy at the registered path.
* ``preflight_fetch``: astra-971-narrow-1125/tmp/preflight_fetch.py (round 2). A fetch at verifier launch changes
  the committed verdict hash. ``preflight_fetch_publication`` moves that fetch to just before stage 1's writes.
* ``rehearsal_fetch``: astra-971-narrow2-1125/tmp/rehearsal_fetch.py (round 3). A fetch at verifier launch
  registers the rehearsal destination as the campaign look directory. ``rehearsal_fetch_publication`` moves that
  fetch to just before the rehearsal's writes. ``rehearsal_fence_branch`` runs the rehearsal from the shared branch,
  where the ledger gate reads the branch, while the fetch registers the destination on main only.

The audit scripts synchronized the fetch with SIGSTOP at the verifier's launch. Here the runner is driven in
process and the named function (``run_verifier`` or the stage's write step) first fetches the second checkout
into origin's main, then runs unchanged. Synthetic data only: every file is generated by the fixture.
"""
