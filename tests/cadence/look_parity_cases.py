def last_line(done):
    text = (done.stderr.strip() or done.stdout.strip()).splitlines()
    return text[-1][:400] if text else ""


class Replay:
    def __init__(self, fx):
        self.fx = fx
        self.controls = []

    # -- commands -----------------------------------------------------------------------------------------------
    def cli(self, script, *args):
        return subprocess.run([sys.executable, "-I", "-B", str(self.fx.repo / script), *map(str, args)],
                              cwd=self.fx.scratch, capture_output=True, text=True, timeout=600)

    def driven(self, argv, **opts):
        opts["repo"] = str(self.fx.repo)
        return subprocess.run([sys.executable, "-I", "-B", "-c", DRIVER, json.dumps(opts), *map(str, argv)],
                              cwd=self.fx.scratch, capture_output=True, text=True, timeout=600)

    def stage1(self, *args, advance=None):
        return self.driven(["stage1", *args], advance=advance)

    def rehearse_rules(self, destination):
        return self.driven(["--rehearsal", destination], entry="rules")

    def need(self, done, what):
        if done.returncode != 0:
            raise SystemExit(f"{what} failed in setup: exit {done.returncode}: {last_line(done)}")
        return done

    def stock_args(self, out=None):
        fx = self.fx
        return ("--manifest", fx.manifest, "--roster", fx.look / M.LOOK_FILES["roster"], "--custody", fx.custody,
                "--out", out or fx.look / M.LOOK_FILES["rules_3_4"])

    def generate(self):
        """The draft producer's verdict on the generated custody, outside every registered root."""
        out = self.fx.scratch / "generated.json"
        self.need(self.cli(PRODUCER, *self.stock_args(out), "--allow-draft"), "draft producer")
        return out

    # -- ledger and git -----------------------------------------------------------------------------------------
    @staticmethod
    def save(path, doc):
        Path(path).write_text(json.dumps(doc, indent=2) + "\n")

    def commit(self, message, branch):
        """Commit, publish to origin's ``branch`` and fetch it back (the audit scripts' helper)."""
        repo = self.fx.repo
        MR.git_commit(repo, message, publish=False)
        MR.git(repo.with_name(repo.name + "-origin.git"), "fetch", "-q", str(repo), "HEAD:refs/heads/" + branch)
        MR.git(repo, "fetch", "-q", "origin", f"refs/heads/{branch}:refs/remotes/origin/{branch}")

    def second_checkout(self, base=None):
        other = self.fx.scratch / "other"
        MR.git(self.fx.scratch, "clone", "-q", "--no-hardlinks", str(self.fx.repo), str(other))
        if base is not None:
            MR.git(other, "checkout", "-q", "--detach", base)
        return other

    def head(self):
        return MR.git(self.fx.repo, "rev-parse", "HEAD").stdout.strip()

    # -- observation ---------------------------------------------------------------------------------------------
    @staticmethod
    def clear(directory, *, receipt=False):
        """Remove a control run's outputs: both stage-1 files, and the stock receipt when asked."""
        for key in ("stage1", "level_r") + (("rules_3_4_receipt",) if receipt else ()):
            name = M.LOOK_FILES.get(key)          # the parent tree has no receipt name
            if name:
                (directory / name).unlink(missing_ok=True)

    @staticmethod
    def snapshot(roots):
        seen = {}
        for label, root in roots.items():
            for path in sorted(Path(root).rglob("*")) if Path(root).exists() else ():
                if path.is_file():
                    seen[f"{label}/{path.relative_to(root)}"] = hashlib.sha256(path.read_bytes()).hexdigest()
        return seen

    def control(self, steps):
        """A run that must succeed on every tree, so a refusal in the act is the act's own."""
        done = [step() for step in steps]
        self.controls.append({"exit": [d.returncode for d in done], "output": [last_line(d) for d in done]})

    def act(self, steps, destination=None):
        """Run the case's steps; every file they create, change or remove in the campaign look directory, the
        default rehearsal directory or the case's destination counts as written."""
        roots = {"look": self.fx.look, "rehearsal": self.fx.rehearsal}
        if destination is not None:
            roots["destination"] = destination
        before = self.snapshot(roots)
        done = [step() for step in steps]
        after = self.snapshot(roots)
        written = sorted(name for name in set(before) | set(after) if before.get(name) != after.get(name))
        return {"exit": [d.returncode for d in done], "output": [last_line(d) for d in done], "written": written}


