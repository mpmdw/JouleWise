# RL-217 A.2 and public RUN_STATE at f8250a29a, items 318, 326, 333, 337, 340,
# 343, 349, 361, 363, 369, 380, 382, 436 and 437. Dates are generated by block.
# Where a Check prints a poll count, use it as the span's minimum generated count.
# Else use 6,600 polls per leg plus 9,000 for span setup, rounded from the checks.
SPANS = (
    ("dev-01-s01", 3, 29375), ("dev-01-s03", 4, 35574), ("dev-01-s04", 5, None),
    ("dev-02-s02", 6, 48062), ("dev-02-s03", 6, 54359),
    ("dev-03-s01", 3, 27414), ("dev-03-s02", 9, None),
    ("dev-04-s01", 6, 50549), ("dev-04-s02", 6, 44194),
    ("dev-05-s01", 6, None), ("dev-05-s02", 6, None),
    ("hp-01-s01", 3, None), ("hp-01-s02", 4, None), ("hp-01-s03", 5, None),
)
STREAMS = re.compile(r"(?:\.(?:csv|jsonl|plist)$|(?:^|/)stream-[^/]+$)")
METER_STREAM = re.compile(r"hazards/meter/stream-[^/]+\.jsonl")


def campaign_plan(roster):
    """Assign each span a synthetic date, clock and mix of prompt cells."""
    span_plan = []
    for sid, leg_count in roster.items():
        block, suffix = sid.rsplit("-", 1)
        day = int(block[-2:]) if block.startswith("dev") else 6
        span_plan.append((block, suffix, f"2026-11-{13 + day:02d}", 3 * int(suffix[1:]),
                          leg_count, "v1.1", "mixed"))
    return span_plan


def pinned_layout(pins):
    """Derive roster and accepted bundle paths from public pin names."""
    legs, bundles = {}, {}
    for span in pins["spans"]:
        sid = span["span_id"]
        if not re.fullmatch(r"(?:dev|hp)-\d{2}-s\d{2}", sid) or sid in legs:
            raise ValueError(f"invalid or repeated span ID: {sid}")
        span_legs = set()
        for file in span["files"]:
            path = file["path"]
            if not custody_pins.safe_relative(path):
                raise ValueError(f"{sid}: invalid relative pin path")
            parts = path.split("/")
            if len(parts) < 3 or parts[0] != "legs":
                continue
            leg = parts[1]
            span_legs.add(leg)
            if len(parts) >= 6 and parts[2:4] == ["runtime", "runs"]:
                bundle = "/".join(parts[3:5])
                if bundles.setdefault(f"{sid}/{leg}", bundle) != bundle:
                    raise ValueError(f"{sid}/{leg}: multiple accepted bundles")
        if not span_legs:
            raise ValueError(f"{sid}: no pinned legs")
        legs[sid] = sorted(span_legs)
    return legs, bundles


def sized_records(path, records, separator, target):
    """Match the byte count with whitespace that leaves the records and their delimiters intact."""
    rows = list(records)
    extra = target - sum(len(row) + len(separator) for row in rows)
    if extra < 0 and path.suffix == ".jsonl":
        rows = [json.dumps(json.loads(row), separators=(",", ":")).encode() for row in rows]
        extra = target - sum(len(row) + len(separator) for row in rows)
    # The stamp reader requires the original CSV header and the writer's literal stamps.
    # Response readers use float() for the power field, which accepts trailing space.
    header = rows[:1] if path.suffix == ".csv" else []
    data = rows[len(header):]
    padding, remainder = divmod(max(extra, 0), len(data))

    def padded_records():
        for i, row in enumerate(data):
            spaces = b" " * (padding + (i < remainder))
            if header:
                stamp, power, fields = row.split(b",", 2)
                yield b",".join((stamp, power + spaces, fields))
            else:
                yield row + spaces

    synth._write_records(path, chain(header, padded_records()), separator)


def write_auxiliary_stream(path, size):
    """Generate the streams that the selected synthetic bundles do not consume."""
    if path.suffix == ".plist":
        row, separator = plistlib.dumps({"synthetic": True}), b"\0"
    elif path.suffix == ".csv":
        row, separator = b"synthetic", b"\n"
    else:
        row, separator = b'{"synthetic":true}', b"\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "wb") as handle:
        if size < len(row) + len(separator):
            handle.write(b"\n" * size)
            return
        count = max(1, size // (64 * 1024))
        width, remainder = divmod(size, count)
        for i in range(count):
            handle.write(row.ljust(width - len(separator) + (i < remainder)) + separator)


def write_campaign(root, size_manifest=None):
    """Write the generated campaign and return its look files and span directories."""
    root = Path(root).resolve()
    leg_ids = bundles = None
    if size_manifest is None:
        roster = {sid: legs for sid, legs, _ in SPANS}
        poll_counts = {sid: polls if polls is not None else 6600 * legs + 9000 for sid, legs, polls in SPANS}
    else:
        pins = size_manifest["inputs"]["pins"]
        leg_ids, bundles = pinned_layout(pins)
        roster = {sid: len(ids) for sid, ids in leg_ids.items()}
        meters = {sid: [] for sid in roster}
        remaining = {}
        for (sid, rel), size in stream_sizes(pins).items():
            path = root / sid / rel
            remaining[path] = size
            if METER_STREAM.fullmatch(rel):
                meters[sid].append(path)
        if not roster or not remaining:
            raise ValueError("the public stream-size inventory is empty")

    def write_records(path, records, separator):
        path = Path(path)
        if path in remaining:
            sized_records(path, records, separator, remaining.pop(path))

    def write_meter(path, pieces, start, end, **kwargs):
        sid = Path(path).parents[2].name
        if size_manifest is None:
            synth._write_meter(path, pieces, start, max(end, start + (poll_counts[sid] - 1) / 5),
                               rate_idx=2, poll_s=0.2, **kwargs)
            return
        # At 50 Hz a 200 ms poll carries ten 20-byte samples, encoded as 400 hex
        # characters, plus around 100 bytes of JSON and clock stamps.
        for target in sorted(meters[sid], key=remaining.__getitem__, reverse=True):
            polls = max(1, round(remaining.pop(target) / 500))
            end = max(end, start + (polls - 1) / 5)
            synth._write_meter(target, pieces, start, end, rate_idx=2, poll_s=0.2, **kwargs)
            start = end = end + 0.2
            pieces, kwargs = [], {**kwargs, "holes": ()}

    tokens = {}
    level, response, _ = synth.build("exact", tokens=tokens, span_plan=campaign_plan(roster), leg_ids=leg_ids,
                                     complete_turns=size_manifest is not None)
    options = {} if size_manifest is None else {"bundle_paths": bundles, "write_records": write_records}
    generated = synth.write_custody(root, level, response, tokens, meter_writer=write_meter, **options)
    if size_manifest is not None:
        for path, size in remaining.items():
            write_auxiliary_stream(path, size)
    return generated, {sid: root / sid for sid in roster}


def stream_sizes(pins):
    return {(span["span_id"], file["path"]): file["size"]
            for span in pins["spans"] for file in span["files"] if STREAMS.search(file["path"])}


def check_sizes(actual, public_manifest):
    """Reject a timing labelled size-matched if any public target is missing or outside 10 percent."""
    expected = stream_sizes(public_manifest["inputs"]["pins"])
    if not expected or set(actual) != set(expected):
        raise ValueError("the public stream-size inventory and generated paths must match")
    mismatches = sum(10 * abs(actual[key] - target) > target for key, target in expected.items())
    if mismatches:
        raise ValueError(f"{mismatches} generated streams fall outside 10% of the public sizes")


def cli(repo, *args, timeout=1500):
    # Small helper around the real isolated entry point. Fixture generation and commits are outside the timing.
    start = perf_counter()
    child = subprocess.run([sys.executable, "-I", "-B", *map(str, args)], cwd=repo, capture_output=True,
                           text=True, timeout=timeout)
    if child.returncode:
        raise RuntimeError(f"generated CLI exit {child.returncode}: {child.stdout.strip()} {child.stderr.strip()}")
    return child.stdout.strip(), perf_counter() - start


# Use the same reservation-name seam as the look's synthetic execution tests
# when the seat cannot create the literal directory. All other checks and the
# stage 2 implementation run on the generated, Git-bound fixture.
SYNTHETIC_RESERVATION_RUNNER = """
from pathlib import Path
import sys
sys.path.insert(0, str(Path.cwd()))
from scripts import cadence_look_run
original = cadence_look_run.release.destinations
def destinations(repo, row):
    private, public = original(repo, row)
    return private.with_name('synthetic-reservation'), public
cadence_look_run.release.destinations = destinations
raise SystemExit(cadence_look_run.main(keep_redirected=True))
"""


def commit(repo, message):
    MR.git_commit(repo, message, publish=False)
    MR.git(repo, "push", "-q", "origin", "HEAD:refs/heads/main")


def prepare(repo, size_manifest):
    manifest = repo / MR.MANIFEST
    doc = M.load_json(manifest)
    custody = Path(doc["custody"]["root"])
    generated, span_dirs = write_campaign(custody, size_manifest)
    look = custody / M.INTERIM_LOOK_ID
    roster = look / M.LOOK_FILES["roster"]
    Path(generated[roster.name]).rename(roster)
    pins = MR.write_pins(repo, span_dirs)
    sizes = stream_sizes(pins)
    if size_manifest is not None:
        check_sizes(sizes, size_manifest)
    leg_count = len({(span["span_id"], pin["path"].split("/")[1]) for span in pins["spans"]
                     for pin in span["files"] if pin["path"].startswith("legs/")})
    print(json.dumps({"spans": len(span_dirs), "legs": leg_count, "stream_files": len(sizes),
                      "stream_bytes": sum(sizes.values()), "size_matched": size_manifest is not None}), flush=True)
    doc["inputs"]["pins"] = pins
    doc["fit"]["twin"] = M.load_json(MR.REPO / MR.MANIFEST)["fit"]["twin"]
    manifest.write_bytes(F.dump(doc))
    producer = "joulewise/cadence_looks/inclusion_34.py"
    generated_verdict = Path(generated["rules_3_4.json"])
    cli(repo, producer, "--roster", roster, "--custody", custody, "--manifest", manifest,
        "--allow-draft", "--out", generated_verdict)
    MR.commit(repo, git_commit_it=False)
    commit(repo, "Commit the generated campaign manifest")

    rules = look / M.LOOK_FILES["rules_3_4"]
    ledger = repo / M.LOOK_LEDGER_PATH
    rows = M.load_json(ledger)
    row = next(row for row in rows["looks"] if row["look_id"] == M.INTERIM_LOOK_ID)
    host, _ = cli(repo, "scripts/cadence_look_run.py", "host-id")
    row.update(roster_sha256=M.sha256_file(roster), verdicts_sha256=M.sha256_file(generated_verdict),
               execution_host=host, custody_root=str(custody), public_root=M.LOOK_PUBLIC_ROOT)
    public = repo / M.public_report_path(row)
    public.parent.mkdir(parents=True)
    ledger.write_bytes(F.dump(rows))
    commit(repo, "Bind generated roster and verdicts")
    cli(repo, producer, "--roster", roster, "--custody", custody, "--manifest", manifest, "--out", rules)
    cli(repo, "scripts/cadence_look_run.py", "stage1")

    stage1 = look / M.LOOK_FILES["stage1"]
    s1 = M.load_json(stage1)
    stage1_sha = M.sha256_file(stage1)
    row.update(status="stage1_committed", stage1_sha256=stage1_sha)
    holds = {flag: "RL-999" for flag in M.STAGE2_HOLD_FLAGS["interim"]
             if s1[flag.split(".")[0]].get(flag.split(".")[1]) is True}
    if holds:
        row["holds_cleared"] = holds  # generated authorization stored only in the fixture's own origin
    ledger.write_bytes(F.dump(rows))
    commit(repo, "Commit generated stage 1")
    return stage1_sha, look, public


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--size-manifest", type=Path, help="public manifest with a complete per-stream size inventory")
    parser.add_argument("--fixture-reservation", action="store_true",
                        help="permit the synthetic reservation name when the literal directory is unavailable")
    args = parser.parse_args()
    size_manifest = M.load_json(args.size_manifest) if args.size_manifest is not None else None
    with tempfile.TemporaryDirectory(prefix="look-scale-results-") as tmp:
        fixture = unittest.TestCase()
        try:
            repo = MR.mini_repo(fixture)
            reservation = MR.synthetic_reservation_name(Path(M.load_json(repo / MR.MANIFEST)["custody"]["root"]))
            if reservation != "RESTRICTED" and not args.fixture_reservation:
                raise RuntimeError("the host does not allow the literal stage-2 reservation directory")
            entry = ("scripts/cadence_look_run.py",) if reservation == "RESTRICTED" else (
                "-c", SYNTHETIC_RESERVATION_RUNNER)
            print(json.dumps({"reservation": reservation}), flush=True)
            stage1_sha, look, public = prepare(repo, size_manifest)
            trials = 1 if size_manifest is not None else 3
            for n in range(1, trials + 1):
                _, elapsed = cli(repo, *entry, "stage2", "--stage1-sha256", stage1_sha)
                result = M.load_json(public)
                agreement = result["twin_agrees"]
                print(json.dumps({"trial": n, "wall_s": round(elapsed, 3), "twin_agrees": agreement}), flush=True)
                if agreement not in ("yes", "no"):
                    raise ValueError("the twin did not complete an evaluable comparison")
                # Preserve each generated result intact and give the next trial a fresh reservation.
                output = Path(tmp).resolve() / f"trial-{n}"
                output.mkdir()
                shutil.move(public, output / public.name)
                shutil.move(look / reservation, output / "result")
        finally:
            fixture.doCleanups()


if __name__ == "__main__":
    main()
