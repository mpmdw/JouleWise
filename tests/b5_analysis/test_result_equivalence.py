class IndependenceTest(_TmpCase):
    def test_stdlib_only_and_runs_isolated_from_its_own_directory(self):
        tree = ast.parse(TOOL.read_text())
        modules = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                modules |= {a.name.split('.')[0] for a in node.names}
            elif isinstance(node, ast.ImportFrom):
                modules.add((node.module or '').split('.')[0])
        modules.discard('__future__')
        self.assertTrue(modules <= set(sys.stdlib_module_names), modules - set(sys.stdlib_module_names))
        self.assertNotIn('joulewise', modules)

    def test_cli_subprocess(self):
        ref, cand, _ = corpus.build_case('decision_extractable', self.tmp)
        env = {k: v for k, v in os.environ.items() if not k.startswith('PYTHON')}
        proc = subprocess.run([sys.executable, '-I', '-B', str(TOOL), '--mode', 'blinded', str(ref), str(cand)],
                              cwd=self.tmp, env=env, capture_output=True, text=True, timeout=120)
        self.assertEqual(proc.returncode, 1, proc.stderr)
        self.assertEqual(proc.stderr, '')
        got = parse_blinded(self, proc.stdout, self.cfg)
        self.assertEqual(got['decisions'], {'mint/extraction-alpha.json:cells'})
        self.assertIn(f'comparator={hashlib.sha256(TOOL.read_bytes()).hexdigest()}', proc.stdout.splitlines()[0])
        proc = subprocess.run([sys.executable, '-I', '-B', str(TOOL), '--mode', 'blinded', '--bogus', str(ref)],
                              cwd=self.tmp, env=env, capture_output=True, text=True, timeout=120)
        self.assertEqual((proc.returncode, proc.stdout, proc.stderr), (2, 'COMPARATOR_ERROR stage=args side=both\n', ''))


