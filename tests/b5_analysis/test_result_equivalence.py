    def test_unordered_exemption(self):
        def order(values):
            def apply(model):
                corpus.file_body(model, 'mint/alpha/calibration_plan.json')['floor_cells'] = values
            return apply
        ref, cand = self.pair(order(['a', 'b']), order(['b', 'a']), name='order')
