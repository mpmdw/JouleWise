class ConfigTest(unittest.TestCase):
    @staticmethod
    def _cfg_dir(tmp: Path, *, tiers=None, exemptions=None):
        for name in (cmp.TIERS_FILE, cmp.EXEMPTIONS_FILE, cmp.OPEN_INDICES_FILE):
            shutil.copy(CONFIG / name, tmp / name)
        if tiers is not None:
            (tmp / cmp.TIERS_FILE).write_text(json.dumps(tiers))
        if exemptions is not None:
            ex = json.loads((CONFIG / cmp.EXEMPTIONS_FILE).read_bytes())
            ex['exemptions'] = exemptions
            (tmp / cmp.EXEMPTIONS_FILE).write_text(json.dumps(ex))
        return tmp

    def test_checked_in_config_loads_and_is_strict(self):
        cfg = cmp.load_config()
        self.assertEqual(cfg.exemptions, [])
        tiers = json.loads((CONFIG / cmp.TIERS_FILE).read_bytes())
        self.assertEqual(tiers['timing_class_policy'], 'strict')
        self.assertEqual(cfg.digests['tiers'], hashlib.sha256((CONFIG / cmp.TIERS_FILE).read_bytes()).hexdigest())

    def test_config_may_only_tighten(self):
        base = json.loads((CONFIG / cmp.TIERS_FILE).read_bytes())
        edits = [
            lambda t: t['decision_rules'].remove(['mint/extraction-*', '$.cells[*].extractable']),
            lambda t: t['registered_rules'].remove(['outputs/projection-*', '$.cells*']),
            lambda t: t['input_record_paths'].remove('$.sealed*'),
            lambda t: t['audit_keys'].append('mean_j'),
            lambda t: t['audit_roles'].append('outputs/*'),
            lambda t: t['audit_key_suffixes'].append('_j'),
            lambda t: t.__setitem__('timing_class_policy', 'lenient'),
            lambda t: t['vocabulary'].append('outputs/projection-alpha.json:cells_v2'),
            lambda t: t.__setitem__('extra', 1),
        ]
        for i, edit in enumerate(edits):
            with self.subTest(edit=i), tempfile.TemporaryDirectory() as d:
                tiers = json.loads(json.dumps(base))
                edit(tiers)
                with self.assertRaises(cmp.ComparatorError) as ctx:
                    cmp.load_config(self._cfg_dir(Path(d), tiers=tiers))
                self.assertEqual(ctx.exception.stage, 'config')
        with tempfile.TemporaryDirectory() as d:
            tiers = json.loads(json.dumps(base))
            tiers['decision_rules'].append(['mint/alpha/calibration_plan.json', '$.fixed_n'])
            tiers['audit_keys'].remove('name')
            cfg = cmp.load_config(self._cfg_dir(Path(d), tiers=tiers))
            self.assertEqual(cfg.tier('mint/alpha/calibration_plan.json', '$.fixed_n', 'fixed_n'), 'D')


class ExemptionsTest(_TmpCase):
    def _load(self, rows):
        d = self.tmp / f'cfg-{len(list(self.tmp.iterdir()))}'
        d.mkdir()
        return cmp.load_config(ConfigTest._cfg_dir(d, exemptions=rows))

    def test_exemption_moves_intermediate_to_audit(self):
        cfg = self._load([{'role': 'mint/alpha/calibration_plan.json', 'path': '$.fixed_n', 'action': 'audit',
                           'reason': 'synthetic test: fixed_n restated by the rewrite'}])
        ref, cand, _ = corpus.build_case('intermediate_calibration_plan', self.tmp)
        rc, text = run_tool(['--mode', 'blinded', ref, cand], cfg=cfg)
        got = parse_blinded(self, text, cfg)
