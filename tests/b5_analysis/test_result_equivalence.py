class TimingClassTest(_TmpCase):
    """Lead ruling 2026-11-02: timing-class refusals are a strict mismatch by default."""

    def _timing(self, pos=None, code='calibration_wall_deadline_fired'):
        return corpus._refused(corpus.POS['5'] if pos is None else pos, code, status='tooling_refusal')

    def test_default_policy_is_strict(self):
        self.assertEqual(self.cfg.timing_policy, 'strict')
        self.assertEqual(sorted(self.cfg.timing_codes),
                         ['calibration_deadline_observer_unavailable', 'calibration_wall_deadline_fired'])
        ref, cand = self.pair(self._timing())
        rc, text = run_tool(['--mode', 'blinded', ref, cand])
        got = parse_blinded(self, text, self.cfg)
        self.assertEqual((rc, got['scope'], got['verdict']), (1, 'full', 'NOT_EQUIVALENT'))
        self.assertIn('record:steps', got['decisions'])

    def test_truncate_policy_compares_the_prefix(self):
        cfg = cmp.load_config(timing_policy='truncate')
        ref, cand = self.pair(self._timing(), name='prefix')
        rc, text = run_tool(['--mode', 'blinded', ref, cand], cfg=cfg)
        got = parse_blinded(self, text, cfg)
        self.assertEqual((rc, got['scope'], got['verdict']), (0, 'prefix', 'EQUIVALENT'), text)
        # A change after the truncation point is outside the compared prefix ...
        late = corpus.CASES['registered_projection_mean'][1]
        ref, cand = self.pair(self._timing(), late, name='late')
        rc, text = run_tool(['--mode', 'blinded', ref, cand], cfg=cfg)
        self.assertEqual(rc, 0, text)
        # ... a change before it is not.
        early = corpus.CASES['decision_kept_unit'][1]
        ref, cand = self.pair(self._timing(), early, name='early')
        rc, text = run_tool(['--mode', 'blinded', ref, cand], cfg=cfg)
        got = parse_blinded(self, text, cfg)
        self.assertEqual((rc, got['scope'], got['decisions']), (1, 'prefix', {'kept-units/alpha.json:cells'}))
        # The observer code truncates too; a non-timing tooling code does not.
        ref, cand = self.pair(self._timing(code='calibration_deadline_observer_unavailable'), name='observer')
        self.assertEqual(run_tool(['--mode', 'blinded', ref, cand], cfg=cfg)[0], 0)
        ref, cand = self.pair(self._timing(code='archive_input_changed'), name='other')
        rc, text = run_tool(['--mode', 'blinded', ref, cand], cfg=cfg)
        self.assertEqual(rc, 1)
        self.assertIn('scope: full', text)

    def test_candidate_timing_refusal_is_never_truncated(self):
        cfg = cmp.load_config(timing_policy='truncate')
        ref, cand = self.pair(None, self._timing())
        rc, text = run_tool(['--mode', 'blinded', ref, cand], cfg=cfg)
        self.assertEqual(rc, 1)
        self.assertIn('scope: full', text)

    def test_same_timing_refusal_on_both_sides_is_a_full_comparison(self):
        ref, cand = self.pair(self._timing(), self._timing())
        rc, text = run_tool(['--mode', 'blinded', ref, cand])
        self.assertEqual(rc, 0, text)
        self.assertIn('scope: full', text)


