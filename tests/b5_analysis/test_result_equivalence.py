        self.assertEqual(rc, 0, text)
        with self.assertRaises(cmp.ComparatorError):
            self._load([{'role': 'kept-units/alpha.json', 'path': '$.cells.f.kept', 'action': 'unordered',
                         'reason': 'synthetic test row, must be refused'}])
        cfg = self._load([{'role': 'mint/alpha/calibration_pla?.json', 'path': '$.floor_cells', 'action': 'unordered',
                           'reason': 'synthetic test: unordered list holding a decision'}])
