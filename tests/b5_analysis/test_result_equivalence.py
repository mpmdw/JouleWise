        self.assertEqual(rc, 1, 'list order is compared by default')
        cfg = self._load([{'role': 'mint/alpha/calibration_plan.json', 'path': '$.floor_cells', 'action': 'unordered',
                           'reason': 'synthetic test: floor cell listing order is not a result'}])
