def _load(name: str, path: Path):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


cmp = _load('jw_b5_equivalence_comparator', TOOL)
corpus = _load('jw_b5_equivalence_corpus', Path(__file__).resolve().parent / 'fixtures' / 'equivalence' / 'corpus.py')

TIER_LINE = re.compile(r'(inputs|decisions|registered|intermediate): (MATCH|DIFFER|NOT_COMPARED)')
FIELD_LINE = re.compile(r'  field ([a-z][a-z_\-/.]*:(?:[A-Za-z_\-]+|<unlisted>))')
HEADER = re.compile(r'B5-EQUIVALENCE blinded tiers=[0-9a-f]{64} exemptions=[0-9a-f]{64} comparator=[0-9a-f]{64}')
TIER_KEYS = ('inputs', 'decisions', 'registered', 'intermediate')


def parse_blinded(test: unittest.TestCase, text: str, cfg) -> dict:
    """Assert the blinded grammar line by line and return {tier: status or field set}."""
    lines = text.splitlines()
    test.assertRegex(lines[0], '^' + HEADER.pattern + '$')
    body = lines[1:]
    joined = '\n'.join(body)
    test.assertIsNone(re.search(r'[0-9]', joined), f'digit outside the header: {joined!r}')
    test.assertIsNone(re.search(r'[0-9a-f]{64}', joined))
    out, current, order = {}, None, {}
    allowed_names = set(cfg.vocabulary) | {f'{c}:<unlisted>' for c in cmp.ROLE_CLASSES + ('unlisted',)}
    for line in body[:-3]:
        m = TIER_LINE.fullmatch(line)
        if m:
            current = m.group(1)
            out[current] = m.group(2) if m.group(2) != 'DIFFER' else set()
            order[current] = []
            continue
        f = FIELD_LINE.fullmatch(line)
        test.assertIsNotNone(f, f'line outside the blinded grammar: {line!r}')
        test.assertIsInstance(out[current], set)
        test.assertIn(f.group(1), allowed_names)
        out[current].add(f.group(1))
        order[current].append(f.group(1))
    test.assertRegex(body[-3], r'^audit: (MATCH|DIFFER \(not printed\)|NOT_COMPARED)$')
    test.assertRegex(body[-2], r'^scope: (full|prefix)$')
    test.assertRegex(body[-1], r'^VERDICT: (EQUIVALENT|NOT_EQUIVALENT)$')
    test.assertEqual(list(out), list(TIER_KEYS))
    for tier in TIER_KEYS:
        if isinstance(out[tier], set):
            test.assertTrue(out[tier], 'DIFFER without a field line')
            test.assertEqual(order[tier], sorted(set(order[tier])), 'field names sorted and de-duplicated')
    out['audit'] = body[-3].split(': ', 1)[1].split(' ')[0]
    out['scope'] = body[-2].split(': ', 1)[1]
    out['verdict'] = body[-1].split(': ', 1)[1]
    return out


def run_tool(args, cfg=None):
    buf = io.StringIO()
    rc = cmp.run([str(a) for a in args], cfg=cfg, out=buf, err=io.StringIO())
    return rc, buf.getvalue()


class _TmpCase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix='jw-b5-eq-')
        self.tmp = Path(self._tmp.name)
        self.cfg = cmp.load_config()

    def tearDown(self):
        for dirpath, dirnames, filenames in os.walk(self.tmp):
            for d in dirnames:
                os.chmod(os.path.join(dirpath, d), 0o700)
        self._tmp.cleanup()

    def pair(self, ref_mut=None, cand_mut=None, name='case'):
        ref_model, cand_model = corpus.base_model(), corpus.base_model()
        if ref_mut:
            ref_mut(ref_model)
        if cand_mut:
            cand_mut(cand_model)
        return corpus.build(ref_model, self.tmp / f'{name}-ref'), corpus.build(cand_model, self.tmp / f'{name}-cand')


class MutationCorpusTest(_TmpCase):
    """Each single registered/decision/refusal/input change is caught; each audit-only change is ignored."""

    def test_identical_trees_match(self):
        ref, cand = self.pair()
        rc, text = run_tool(['--mode', 'blinded', ref, cand])
        self.assertEqual(rc, 0, text)
        got = parse_blinded(self, text, self.cfg)
        self.assertEqual([got[t] for t in TIER_KEYS], ['MATCH'] * 4)
        self.assertEqual((got['audit'], got['scope'], got['verdict']), ('MATCH', 'full', 'EQUIVALENT'))
        rc, text = run_tool(['--mode', 'open', '--no-report', ref, cand])
        self.assertEqual(rc, 0, text)
        self.assertIn('VERDICT: EQUIVALENT', text)

    def test_every_case(self):
        self.assertGreaterEqual(len(corpus.CASES), 40)
        for name in corpus.CASES:
            with self.subTest(case=name):
                ref, cand, expected = corpus.build_case(name, self.tmp)
                rc, text = run_tool(['--mode', 'blinded', ref, cand])
                got = parse_blinded(self, text, self.cfg)
                failing = {t: v for t, v in expected.items() if t in TIER_KEYS and isinstance(v, set)}
                want_verdict = 'NOT_EQUIVALENT' if failing else 'EQUIVALENT'
                self.assertEqual(got['verdict'], want_verdict, text)
                self.assertEqual(rc, 1 if failing else 0, text)
                for tier in TIER_KEYS:
                    self.assertEqual(got[tier], expected.get(tier, 'MATCH'), f'{tier}\n{text}')
                if 'audit' in expected:
                    self.assertEqual(got['audit'], expected['audit'], text)
                # Open mode agrees on the verdict and prints both exact tokens.
                orc, otext = run_tool(['--mode', 'open', '--no-report', ref, cand])
                self.assertEqual(orc, rc, otext)
                self.assertIn(f'VERDICT: {want_verdict}', otext)

    def test_exact_tokens_are_printed_in_open_mode(self):
        ref, cand, _ = corpus.build_case('registered_token_one_point_zero_vs_one', self.tmp)
        rc, text = run_tool(['--mode', 'open', '--no-report', ref, cand])
        self.assertEqual(rc, 1)
        self.assertIn('outputs/projection-alpha.json $.cells[0].lower_j: 2.0 -> 2', text)
        ref, cand, _ = corpus.build_case('registered_negative_zero', self.tmp)
        rc, text = run_tool(['--mode', 'open', '--no-report', ref, cand])
        self.assertIn('$.cells[0].floor_abs_j: 0.0 -> -0.0', text)

    def test_referential_break_is_caught(self):
        ref, cand = self.pair(name='break')
        name = _extraction_name(cand)
        data = (cand / 'dry-run' / 'restricted' / name).read_bytes().replace(b'/synthetic/runs', b'/synthetic/other')
        corpus.recommit(cand, name, data)
        rc, text = run_tool(['--mode', 'blinded', ref, cand])
        got = parse_blinded(self, text, self.cfg)
        self.assertEqual(rc, 1)
        # The edited field is audit (runs_root); the stale digest reference is the failure.
        self.assertEqual(got['intermediate'], {'mint/floor-mint-inputs.json:producer_plans'})
        self.assertEqual([got[t] for t in ('inputs', 'decisions', 'registered')], ['MATCH'] * 3)


def _extraction_name(root: Path) -> str:
    record = json.loads((root / 'dry-run' / corpus.RECORD).read_bytes())
    return next(o['name'] for row in record['steps'] for o in row['outputs'] if 'extraction-alpha' in o['name'])


class BlindedLeakTest(_TmpCase):
    """Blinded output carries only MATCH/DIFFER and vocabulary names: no value, count, id or code."""

    SENTINELS = (corpus.SENTINEL_MEAN, corpus.SENTINEL_MEAN_MUTANT, corpus.SENTINEL_BUNDLE, corpus.SENTINEL_CODE,
                 corpus.SENTINEL_CODE_MUTANT, corpus.SENTINEL_PLAN, corpus.CORPUS_INDEX_SHA256, corpus.COMMIT,
                 'a' * 40, 'bbbbbbbbbb', '99.03181', 'q02')

    def test_no_value_count_or_identifier_in_blinded_output(self):
        for name in corpus.CASES:
            with self.subTest(case=name):
                ref, cand, _ = corpus.build_case(name, self.tmp)
                rc, text = run_tool(['--mode', 'blinded', ref, cand])
                parse_blinded(self, text, self.cfg)
                body = text.split('\n', 1)[1]
                for s in self.SENTINELS:
                    self.assertNotIn(s, body)
                self.assertNotIn('[', body)  # no list index or count
                mirrored = (cand / 'equivalence' / 'BLINDED-VERDICT.txt').read_text()
                self.assertEqual(mirrored, text)

    def test_valued_report_is_restricted(self):
        ref, cand, _ = corpus.build_case('registered_projection_mean', self.tmp)
        rc, text = run_tool(['--mode', 'blinded', ref, cand])
        self.assertEqual(rc, 1)
        eq = cand / 'equivalence'
        self.assertEqual(stat.S_IMODE(os.lstat(eq).st_mode), 0o700)
        self.assertEqual(stat.S_IMODE(os.lstat(eq / 'restricted').st_mode), 0o700)
        reports = sorted((eq / 'restricted').glob('*.blinded.json'))
        self.assertEqual(len(reports), 1)
        self.assertEqual(stat.S_IMODE(os.lstat(reports[0]).st_mode), 0o600)
        report = json.loads(reports[0].read_text())
        row = report['differences']['registered'][0]
        self.assertEqual((row['ref'], row['cand']), (['#f', corpus.SENTINEL_MEAN], ['#f', corpus.SENTINEL_MEAN_MUTANT]))
        self.assertEqual(sorted(p.name for p in eq.iterdir()), ['BLINDED-VERDICT.txt', 'restricted'])
        # Neither tree's dry-run directory is written.
        self.assertFalse(any('equivalence' in str(p) for p in (ref / 'dry-run').rglob('*')))
        rc2, _ = run_tool(['--mode', 'blinded', ref, cand])
        self.assertEqual(len(sorted((eq / 'restricted').glob('*.json'))), 2, 'second run keeps the first report')

    def test_comparator_error_prints_only_stage_and_side(self):
        ref, cand = self.pair(name='err')
        name = _extraction_name(cand)
        path = cand / 'dry-run' / 'restricted' / name
        path.write_bytes(path.read_bytes().replace(b'false', b'true', 1))
        rc, text = run_tool(['--mode', 'blinded', ref, cand])
        self.assertEqual(rc, 2)
        self.assertEqual(text, 'COMPARATOR_ERROR stage=authenticate side=cand\n')
        errors = list((cand / 'equivalence' / 'restricted').glob('comparator-error*.txt'))
        self.assertEqual(len(errors), 1)
        self.assertIn('does not match its committed sha256', errors[0].read_text())


